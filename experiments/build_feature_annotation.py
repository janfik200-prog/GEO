def describe(feat: str, grp: str) -> str:
    if feat in EXACT:
        return EXACT[feat]
    std = feat.endswith("_std")
    base = feat[:-4] if std else feat
    suf = " -- std по сценам (межгодовая/внутриячеечная изменчивость)" if std else ""

    if grp == "ast":
        m = re.match(r"ast_(b0[1-9])$", base)
        if m:
            return f"ASTER {ASTER_BANDS[m.group(1)]}, сырое отражение" + suf
        key = base.replace("ast_", "")
        if key in INDEX_MEANING:
            return f"ASTER: {INDEX_MEANING[key]}" + suf
    if grp in ("s2", "s2raw"):
        m = re.match(r"s2_(b\w+)$", base)
        if m and m.group(1) in S2_BANDS:
            return f"Sentinel-2 {S2_BANDS[m.group(1)]}, сырое отражение" + suf
        key = base.replace("s2_", "")
        if key in INDEX_MEANING:
            return f"Sentinel-2: {INDEX_MEANING[key]}" + suf
        if key == "valid_frac":
            return "Доля валидных (безоблачных) наблюдений в ячейке"
        if key == "n_obs":
            return "Число сцен, вошедших в композит"
    if grp == "l8":
        key = base.replace("l8_", "")
        band_names = {
            "blue": "канал blue", "green": "канал green", "red": "канал red",
            "nir08": "канал NIR", "swir16": "канал SWIR 1", "swir22": "канал SWIR 2",
        }
        if key in band_names:
            return f"Landsat 8/9 {band_names[key]}, сырое отражение" + suf
        if key in INDEX_MEANING:
            return f"Landsat 8/9: {INDEX_MEANING[key]}" + suf
    if grp == "ls":
        m = re.match(r"ls_(ch\d)$", base)
        if m:
            return f"Landsat 7 ETM+ {LS_BANDS[m.group(1)]}, сырое отражение"
    if grp == "gm":
        key = base.replace("gm_", "")
        if key in GM_FIELDS:
            return f"Грав/магниторазведка: {GM_FIELDS[key]}"
    if grp == "pf":
        key = base.replace("pf_", "")
        if key in PF_FIELDS:
            return f"Трансформанта потенциального поля: {PF_FIELDS[key]}"
    if grp == "s1":
        key = base.replace("s1_", "")
        pol = {"vv": "поляризация VV, дБ", "vh": "поляризация VH, дБ", "vv_vh": "отношение поляризаций VV/VH"}
        if key in pol:
            return f"Sentinel-1: обратное рассеяние, {pol[key]}" + suf
        if key == "valid_frac":
            return "Доля валидных наблюдений в ячейке"
        if key == "n_obs":
            return "Число сцен, вошедших в композит"
    if grp == "psr":
        key = base.replace("psr_", "")
        pol = {
            "hh": "поляризация HH", "hv": "поляризация HV", "hh_hv": "отношение поляризаций HH/HV",
            "linci": "локальный угол падения (геометрическая поправка рельефа)",
        }
        if key in pol:
            return f"ALOS PALSAR-2: {pol[key]}" + suf
    return f"Признак группы \"{grp}\" (см. описание группы)"


def main() -> None:
    df = pd.read_csv(IN_PATH)
    df["источник"] = df["группа"].map(SOURCE)
    df["описание"] = df.apply(lambda r: describe(r["признак"], r["группа"]), axis=1)

    missing = df[df["описание"].str.contains("см. описание группы")]
    print("Без точного описания:", len(missing))
    if len(missing):
        print(missing[["признак", "группа"]].to_string(index=False))

    df.to_csv(OUT_PATH, index=False, encoding="utf-8-sig")
    print("OK, rows:", len(df))


if __name__ == "__main__":
    main()
