"""Признаки окрестности для табличной постановки: структурный тензор и гребни.

ЗАЧЕМ. В поячеечной таблице у модели нет ничего о том, что ячейка лежит НА
ЛИНИИ: она видит спектр точки и только его. На карте Анабара это видно прямо
глазами — отобранные ячейки складываются в пятна по типу поверхности, а не в
линеаменты. Здесь та же таблица дополняется тем, чем свёрточная сеть у неё
выигрывала: локальной анизотропией и «гребневостью» — но без свёрточной сети,
строк столько же, модель остаётся неглубокой.

ЧТО СЧИТАЕТСЯ. Для каждого базового канала на нескольких масштабах:

* ``coh``    — когерентность структурного тензора: 0 — изотропная текстура,
               1 — строго однонаправленная. Это и есть «здесь есть линия».
* ``eng``    — логарифм следа тензора: сколько вообще градиента на масштабе.
* ``cos/sin``— направление (в удвоенном угле, потому что направление линии
               определено с точностью до разворота на 180°).
* ``rdg``    — знаковое главное собственное число гессиана: тёмный линеамент и
               светлый хребет получают разный знак, модель разбирается сама.

ВСЁ СЧИТАЕТСЯ ТОЛЬКО ИЗ СНИМКА. Разметка сюда не входит ни в каком виде.

НОСИТЕЛЬ ПРИЗНАКА И БУФЕР РАЗБИЕНИЯ. Сглаживание с sigma = 2 км имеет носитель
около 3*sigma = 6 км, то есть шире буфера блочного разбиения (2 км). Если
считать окрестность по всему растру сразу, признак проверочной ячейки собран в
том числе из обучающих полос: разлом, пересекающий обучающую полосу, оставляет
размазанный след и по ту сторону буфера, модель узнаёт его продолжение и
проверка перестаёт быть независимой. Поэтому ``neigh_stack`` принимает
``support`` — маску, ИЗ КОТОРОЙ берётся окрестность. Признаки обучения
считаются с ``support = train``, признаки проверки — с ``support = val``, и
носитель признака физически не пересекает границу. Нормированная свёртка это
позволяет: ячейки вне ``support`` не входят ни в числитель, ни в знаменатель.

СГЛАЖИВАНИЕ С МАСКОЙ. Кадр повёрнут, углы растра пустые. Обычный гауссов
фильтр размазал бы границу кадра внутрь на весь масштаб и дал бы у края ложный
«линеамент». Поэтому свёртка нормированная: отдельно сглаживается величина,
отдельно маска валидности, и одно делится на другое.
"""
from __future__ import annotations

import numpy as np

#: Масштабы окрестности, м. 500 м — ближайший к полуширине разметки (150 м) с
#: запасом на ошибку положения линии; 2 км — верх диапазона, дальше окно шире
#: типичного расстояния между соседними разломами и начинает их смешивать.
SCALES_M = (500.0, 1000.0, 2000.0)

#: На каких каналах считать окрестность. Не на всех десяти: у когерентностей
#: одного лета структура почти одинаковая, и десять почти одинаковых наборов
#: признаков только раздули бы таблицу. Взяты три независимых источника —
#: оптика, радар и интерферометрическая когерентность.
BASE = ("gray", "vv", "coh_summer_vv_COH12")

#: Внутренний масштаб производной, ячеек. Меньше 1 — считаем шум датчика,
#: больше 2 — теряем узкие линеаменты ещё до структурного тензора.
INNER_PX = 1.5


def _gsm(a: np.ndarray, mask: np.ndarray, s: float) -> np.ndarray:
    """Гауссово сглаживание, нормированное на маску валидных ячеек."""
    from scipy.ndimage import gaussian_filter

    num = gaussian_filter(np.where(mask, a, 0.0).astype("float32"), s, mode="nearest")
    den = gaussian_filter(mask.astype("float32"), s, mode="nearest")
    return num / np.maximum(den, 1e-3)


def _norm(a: np.ndarray, mask: np.ndarray) -> np.ndarray:
    """Та же робастная нормировка (медиана и IQR), что у базовых каналов."""
    v = a[mask & np.isfinite(a)]
    med = np.median(v) if v.size else 0.0
    q1, q3 = (np.percentile(v, [25, 75]) if v.size else (0.0, 1.0))
    out = (a - med) / ((q3 - q1) or 1.0)
    return np.nan_to_num(out, nan=0.0, posinf=0.0, neginf=0.0).astype("float32")


def _one_channel(a: np.ndarray, mask: np.ndarray, s_px: float
                 ) -> dict[str, np.ndarray]:
    """Пять признаков окрестности одного канала на одном масштабе."""
    from scipy.ndimage import gaussian_filter

    sm = _gsm(a, mask, INNER_PX)
    gy, gx = np.gradient(sm)
    gy = np.where(mask, gy, 0.0)
    gx = np.where(mask, gx, 0.0)

    jxx = _gsm(gx * gx, mask, s_px)
    jyy = _gsm(gy * gy, mask, s_px)
    jxy = _gsm(gx * gy, mask, s_px)
    tr = jxx + jyy
    disc = np.sqrt((jxx - jyy) ** 2 + 4.0 * jxy ** 2)
    th2 = np.arctan2(2.0 * jxy, jxx - jyy)      # уже удвоенный угол

    big = _gsm(a, mask, max(s_px * 0.5, INNER_PX))
    hxx = gaussian_filter(big, s_px * 0.5, order=(0, 2), mode="nearest")
    hyy = gaussian_filter(big, s_px * 0.5, order=(2, 0), mode="nearest")
    hxy = gaussian_filter(big, s_px * 0.5, order=(1, 1), mode="nearest")
    half = 0.5 * (hxx + hyy)
    rad = np.sqrt((0.5 * (hxx - hyy)) ** 2 + hxy ** 2)
    lam1, lam2 = half + rad, half - rad
    ridge = np.where(np.abs(lam1) >= np.abs(lam2), lam1, lam2)

    return {"coh": disc / np.maximum(tr, 1e-8),
            "eng": np.log(tr + 1e-8),
            "cos": np.cos(th2),
            "sin": np.sin(th2),
            "rdg": ridge}


#: Во сколько sigma оценивается носитель гауссова окна. Всё, что дальше 3 sigma,
#: весит меньше 1% и на признак уже не влияет.
SUPPORT_SIGMAS = 3.0


def support_radius_m(scales_m: tuple[float, ...] = SCALES_M) -> float:
    """Насколько широкую окрестность реально видит признак, м."""
    return SUPPORT_SIGMAS * max(scales_m)


def neigh_stack(x: np.ndarray, use: tuple[str, ...], valid: np.ndarray,
                res_m: float, base: tuple[str, ...] = BASE,
                support: np.ndarray | None = None
                ) -> tuple[np.ndarray, tuple[str, ...]]:
    """Каналы окрестности поверх уже нормированного стека ``x`` (C,H,W).

    ``support`` — маска, из которой берётся окрестность (по умолчанию ``valid``,
    то есть весь кадр). При блочной проверке сюда подаётся своя часть разбиения,
    см. блок про носитель признака в шапке модуля.

    Возвращает ``(доп. каналы, их имена)``. Считается по нормированным базовым
    каналам, а не по сырым: у структурного тензора масштаб входа сокращается в
    когерентности, но не в энергии и гребне, и одна нормировка на входе избавляет
    от разнобоя между площадками.
    """
    sup = valid if support is None else (support & valid)
    idx = {n: i for i, n in enumerate(use)}
    out, names = [], []
    for ch in base:
        if ch not in idx:
            continue
        a = x[idx[ch]]
        for s_m in SCALES_M:
            s_px = s_m / res_m
            for key, val in _one_channel(a, sup, s_px).items():
                out.append(_norm(val, sup))
                names.append(f"{ch}_{key}{int(s_m)}")
    if not out:
        raise SystemExit("ни одного базового канала для признаков окрестности")
    return np.stack(out), tuple(names)
