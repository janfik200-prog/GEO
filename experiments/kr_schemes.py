# ---------------------------------------------------------------- рисунок 3
def kr3(путь: Path) -> None:
    """Три состояния свидетельства и их распространение вверх."""
    fig, ax = холст(5.6)
    шапка(ax, "Три состояния свидетельства и их распространение", "охра",
          высота=11.0)

    состояния = [("Наблюдается", "значение в отрезке [0; 1]", "зелёный"),
                 ("%s Не наблюдается" % ПУСТО,
                  "нет канала либо не выполнено условие", "жёлтый"),
                 ("Запрещено", "ячейка исключается из расчёта", "красный")]
    w, h = 31.6, 17.0
    for i, (т, н, тон) in enumerate(состояния):
        карточка(ax, 1.0 + i * 33.2, 68.0, w, h, т, [н], тон=тон,
                 центр=True, кегль=ОСН, полоса=6.4)

    цепь = [("Признак", ("часть входов", "помечена ⊥"), "синий"),
            ("Критерий", ("среднее", "по остальным"), "охра"),
            ("Объект", ("среднее", "по остальным"), "сирень"),
            ("Звено", ("все входы ⊥ —", "звено тоже ⊥"), "зелёный"),
            ("Итог P(x)", ("звено выпадает", "из свёртки"), "зелёный"),
            ("Итог C(x)", ("ниже ровно", "на 1/M"), "красный")]
    w2, h2, шаг = 15.1, 17.0, 16.4
    for i, (т, строки, тон) in enumerate(цепь):
        x = 1.0 + i * шаг
        карточка(ax, x, 42.0, w2, h2, т, строки, тон=тон, центр=True,
                 кегль=ОСН - 0.4, полоса=6.0)
        if i:
            стрелка(ax, x - 1.3, 50.5, x - 0.3, 50.5, толщина=1.3)

    панель(ax, 1.0, 2.0, 98.0, 34.0, "Почему не нулём и не серединой",
           ["Ноль утверждает «проверено и не выполнено» и читается как "
            "отрицание: отсутствующий канал",
            "тогда снижает оценку наравне с проверенным несовпадением. "
            "Значение 0,5 утверждает",
            "«известно наполовину» и добавляет в карту сведения, которых "
            "нет. Отдельное состояние",
            "переносит незнание из оценки в обеспеченность — обе величины "
            "остаются содержательными,",
            "а ячейка с пропуском отличима от ячейки с проверенным "
            "несовпадением."])
    сохранить(fig, путь)


