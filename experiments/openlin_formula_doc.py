def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rel = Path("..") / OUT                      # md лежит в presentation/

    lines = ["# Линеаменты по космоснимкам: формулы и обозначения", ""]
    lines += [p for para in INTRO for p in (para, "")]

    lines += ["## Откуда берутся данные", ""]
    lines += [p for para in DATA_INTRO for p in (para, "")]
    lines += ["| канал | что это | как получен |", "|---|---|---|"]
    for name, what, how in DATA_ROWS:
        lines.append(f"| {cell(name)} | {cell(what)} | {cell(how)} |")
    lines.append("")
    lines += [p for para in DATA_TAIL for p in (para, "")]

    lines += ["## Цепочка величин", "",
              "Каждая следующая величина считается из предыдущей; у каждой "
              "формулы это повторено подробно в разделе «Откуда берётся».", "",
              "| величина | что это | где появляется |", "|---|---|---|"]
    for name, what, where in CHAIN:
        lines.append(f"| {cell(name)} | {cell(what)} | {cell(where)} |")
    lines.append("")

    lines += ["## Общие обозначения", "",
              "Эти обозначения встречаются в нескольких формулах сразу и "
              "дальше не повторяются.", "",
              "| обозначение | что это |", "|---|---|"]
    for s_, desc in COMMON:
        lines.append(f"| {cell(sym(s_))} | {cell(desc)} |")
    lines.append("")

    n, gaps = 0, []
    for title, intro, items in SECTIONS:
        lines += ["---", "", f"## {title}", "", intro, ""]
        for it in items:
            render(it["id"], it["tex"])
            n += 1
            syms = it["syms"] + EXTRA_SYMS.get(it["id"], [])
            gap = missing(it["tex"], syms)
            if gap:
                gaps.append(f"{it['id']}: {', '.join(gap)}")
            lines += [f"### {it['title']}", "",
                      f"![{it['title']}]"
                      f"({(rel / (it['id'] + '.png')).as_posix()})", "",
                      f"**Что это.** {it['what']}", "",
                      f"**Откуда берётся.** {it['src']}", "",
                      "| обозначение | что это |", "|---|---|"]
            seen = set()
            for s_, desc in syms:
                key = sym(s_)
                if key in seen:              # символ уже описан в этой таблице
                    continue
                seen.add(key)
                lines.append(f"| {cell(key)} | {cell(desc)} |")
            lines += ["", f"**Как читается.** {it['read']}", "",
                      f"**Почему так.** {it['why']}", "",
                      f"**Значения.** {it['vals']}", ""]

    MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"формул отрисовано: {n}")
    if gaps:
        print("НЕ ОПИСАНЫ символы:")
        for g in gaps:
            print("  " + g)
    else:
        print("все символы формул описаны")
    print(f"сохранено: {MD}")
    docx = convert(MD)
    print(f"сохранено: {docx}")


if __name__ == "__main__":
    main()
