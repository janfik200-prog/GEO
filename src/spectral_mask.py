"""Маска «спектр действительно измерил породу».

Спектральные признаки Sentinel-2 посчитаны во всех ячейках листа, но открытый
грунт есть далеко не везде: при доле обнажённости от 2% таких ячеек 35% на
основном листе и 30% на широкой сетке. Там, где поверхность закрыта
растительностью, индекс всё равно имеет число — и модель учит на нём ландшафт,
а не породу.

Замер 07.09.2026 (`experiments/spectral_exposure*.py`, схема — полосы с
разрывом 15 км, сглаживание рабочей точки): совпадение с критериальным
прогнозом по верхним 10% после снятия наклона составляет 0.279 при спектрах,
посчитанных везде; 0.337 если спектры убрать совсем; **0.362** если оставить их
только на обнажённых ячейках, а в остальных поставить пропуск (гистограммный
бустинг обрабатывает пропуски сам) и добавить признак-флаг «спектр измерен».

Контроль отделяет два эффекта: случайная маска той же доли ячеек даёт
0.328 ± 0.005 по трём зёрнам — то есть бо́льшая часть прибавки это удаление
вредного ландшафтного сигнала. Сверх случайной маски география обнажённости
даёт +0.029 [+0.009; +0.055] (блочный бутстрэп по блокам 10 км).

Порог выбран не по метрике: она держится на плато 0.34–0.36 при любом пороге от
0.02 до 0.35, поэтому взят край плато — он оставляет измеренными больше ячеек.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

# Доля открытого грунта в ячейке, начиная с которой спектр считается измерением
# породы. Край плато по метрике (см. докстринг модуля).
BARE_MIN = 0.02

BARE_COL = "s2_bare_frac"
FLAG_COL = "спектр_измерен"

# Служебные столбцы съёмки — не спектр, маскировать их нечего.
_SERVICE = ("s2_valid_frac", "s2_n_obs", BARE_COL)


def spectral_columns(columns) -> list[str]:
    """Столбцы, значение которых имеет смысл только на открытом грунте."""
    return [c for c in columns if c.startswith("s2_") and c not in _SERVICE]


def exposure_mask(df: pd.DataFrame, threshold: float = BARE_MIN) -> np.ndarray:
    """Булева маска ячеек, где спектр измерил породу.

    Ячейки без данных об обнажённости считаются неизмеренными: пропуск в
    маске — это «не знаем», а не «открыто».
    """
    bare = df[BARE_COL].to_numpy(dtype=float)
    return np.isfinite(bare) & (bare >= threshold)


def apply(df: pd.DataFrame, threshold: float = BARE_MIN,
          add_flag: bool = True) -> pd.DataFrame:
    """Спектральные столбцы — только на обнажённых ячейках, плюс признак-флаг.

    Возвращается копия; исходный кадр не меняется. Если спектральных столбцов
    в кадре нет, кадр возвращается как есть (с флагом, если он запрошен и есть
    чем его посчитать).
    """
    out = df.copy()
    keep = exposure_mask(df, threshold)
    cols = spectral_columns(df.columns)
    if cols:
        out.loc[~keep, cols] = np.nan
    if add_flag:
        out[FLAG_COL] = keep.astype(float)
    return out
