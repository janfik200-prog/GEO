def _copy_pPr_style(src_p, dst_p):
    pPr = src_p._p.find(qn("w:pPr"))
    if pPr is not None:
        dst_p._p.insert(0, copy.deepcopy(pPr))


def main() -> None:
    d = docx.Document(PATH)
    list_item_template = d.paragraphs[1]   # существующий маркированный пункт (numId=1, ilvl=0)
    plain_template = d.paragraphs[3]        # существующая обычная строка "chN – ..."

    d.add_paragraph("")  # разделитель перед новым блоком
    heading = d.add_paragraph("Данные, добавленные в датасете v5 (собственная докачка/сборка "
                               "проекта поверх исходной поставки СБОРКА_ДОП)")
    heading.runs[0].bold = True

    for title, fields in SECTIONS:
        p = d.add_paragraph(title)
        _copy_pPr_style(list_item_template, p)

        props = d.add_paragraph("свойства:")
        _copy_pPr_style(plain_template, props)
        # "свойства:" в оригинале - Normal без bullet, но у plain_template нет pPr (Normal) —
        # copy делает pPr пустым, что ок (Normal и есть отсутствие pPr/bullet).

        for name, desc in fields:
            fp = d.add_paragraph(f"{name} – {desc};")
            _copy_pPr_style(plain_template, fp)

    d.save(PATH)
    print(f"сохранено: {PATH}")


if __name__ == "__main__":
    main()
