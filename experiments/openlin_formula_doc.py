def sym(s: str) -> str:
    """Обозначение из TeX в обычный текст: ``$\\lambda_\\pm$`` -> ``λ±``."""
    s = s.strip()
    if s.startswith("$") and s.endswith("$"):
        s = s[1:-1]
    # надстрочные знаки — комбинирующими символами, иначе \bar f и \hat f
    # превратились бы в одинаковое «f»
    s = re.sub(r"\\bar\s*(\w)", "\\1\u0304", s)
    s = re.sub(r"\\hat\s*(\w)", "\\1\u0302", s)
    s = re.sub(r"\\math(?:rm|cal|bf)\{(.*?)\}", r"\1", s)
    for a, b in sorted(_TEX.items(), key=lambda kv: -len(kv[0])):
        s = s.replace(a, b)
    s = re.sub(r"_\{(\w+)\}", lambda m: m.group(1).translate(_SUB)
               if m.group(1).isdigit() else "_" + m.group(1), s)
    s = re.sub(r"_(\d)", lambda m: m.group(1).translate(_SUB), s)
    s = re.sub(r"_([+\-])", lambda m: m.group(1).translate(_SUB), s)
    s = s.replace("{", "").replace("}", "").replace("$", "")
    s = s.replace("^ᵀ", "ᵀ").replace("^-1/2", "^(−1/2)").replace("^-1", "⁻¹")
    s = s.replace("· ", "·").replace("± ", "±").replace("  ", " ")
    s = re.sub(r"(?<=[(\[⟨])\s+", "", s)
    s = re.sub(r"\s+(?=[)\]⟩])", "", s)
    s = s.replace(HIDE_L, "{").replace(HIDE_R, "}")
    s = s.replace("Δ ", "Δ")
    return re.sub(r",(?=\S)", ", ", s).strip()


def cell(s: str) -> str:
    """Текст ячейки таблицы: вертикальная черта разделяет колонки в Markdown,
    поэтому «|L|» (число элементов) пишется знаком деления U+2223."""
    return s.replace("|", "∣")


