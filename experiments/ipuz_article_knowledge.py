def формула(doc: Document, текст: str, номер: str) -> None:
    """Формула по принятой у нас форме: по центру, номер в скобках справа.

    В шаблоне конференции формул нет и правил для них не задано, поэтому
    применяется обычная для русскоязычных изданий форма: формула отдельным
    абзацем по центру, номер в круглых скобках прижат к правому полю
    табуляцией.
    """
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.space_before, pf.space_after = Pt(6), Pt(6)
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.tab_stops.add_tab_stop(Cm(16.5), WD_TAB_ALIGNMENT.RIGHT)
    p.add_run(текст).italic = True
    p.add_run("\t(%s)" % номер)


def по_шаблону(doc: Document) -> None:
    """Довести вёрстку до буквы шаблона конференции.

    Шаблон предписывает в тексте статьи «интервал перед текстом равным
    0,42 см» — это 12 пт перед каждым абзацем основного текста (в самом
    шаблоне у такого абзаца ``space_before = 12``). Абзацы основного текста
    опознаются по отступу первой строки 1,25 см; служебные элементы (УДК,
    авторы, аннотация, ключевые слова, подписи, литература) идут с другим
    отступом и не трогаются.

    Там же: подпись таблицы — полужирная, по правому краю, вида
    «Таблица 1. Наименование»; УДК — полужирный.
    """
    основной = 0
    for p in doc.paragraphs:
        pf = p.paragraph_format
        # Отступ 1,25 см у основного текста наследуется от стиля, поэтому
        # «не задан явно» — тоже признак абзаца основного текста.
        свой = pf.first_line_indent
        if свой is None or abs(свой.cm - ОТСТУП_АБЗАЦА) < 0.01:
            pf.space_before = Pt(ИНТЕРВАЛ_ПЕРЕД)
            основной += 1
        t = p.text.strip()
        if t.startswith("УДК") or t.startswith("Таблица "):
            for r in p.runs:
                r.bold = True
    print("интервал 12 пт проставлен абзацам основного текста:", основной)


