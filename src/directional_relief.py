"""Направленная фильтрация рельефа: отклик линейных форм по азимутам простирания.

ЗАЧЕМ. Проверка `experiments/factor_from_remote.py` показала, что разломные
слои критериальной формулы не восстанавливаются по нашим дистанционным
признакам вообще (ROC 0.45–0.53 при случайном 0.5), хотя именно разломы весят в
формуле больше всего. Имеющиеся признаки линеаментов (`src/lineaments.py`)
собирают все направления в один скаляр: плотность линий, расстояние до
ближайшей. Разлом же — это прежде всего ОРИЕНТИРОВАННАЯ форма, и две системы
разломов на листе различаются именно простиранием (северо-западное и
северо-восточное). Скаляр, сложенный по всем азимутам, эту разницу стирает.

ЧТО СЧИТАЕТСЯ. Рельеф в исходном разрешении 100 м сворачивается с вытянутыми
ядрами, каждое из которых настроено на своё простирание:

* **отклик долины/гребня** — вторая производная гауссиана поперёк простирания,
  сглаженная вдоль него. Спрямлённая долина по азимуту θ даёт максимум именно
  на ядре θ и почти ноль на ядре θ+90°;
* **отклик уступа** — первая производная поперёк простирания, сглаженная вдоль.
  Разлом со смещением по вертикали выражен уступом, а не долиной.

Отношение длины ядра к ширине фиксировано (`ELONGATION`): изотропное ядро
меряет расчленённость, вытянутое — линейность. Масштабы берутся кратными, чтобы
поймать и узкие спрямлённые долины, и широкие уступы.

Из откликов по азимутам собираются признаки на ячейку рабочей сетки: сам отклик
по каждому азимуту, максимум по азимутам, анизотропия (насколько один азимут
выделяется над остальными) и преобладающее направление через удвоенный угол —
у линии нет начала и конца, 10° и 190° это одно простирание.

Азимуты — географические, от севера по часовой стрелке, в диапазоне 0–180°.
"""

from __future__ import annotations

import numpy as np
from scipy.signal import fftconvolve

#: Отношение длины ядра к его ширине. 6 — линия должна быть заметно длиннее,
#: чем широка, иначе фильтр меряет обычную шероховатость рельефа.
ELONGATION: float = 6.0

#: Ширины ядра поперёк простирания, в ячейках рельефа (шаг 100 м).
SCALES_CELLS: tuple[float, ...] = (2.0, 4.0)

#: Шаг перебора простираний, градусы.
AZIMUTH_STEP: float = 15.0


def azimuths(step: float = AZIMUTH_STEP) -> np.ndarray:
    """Простирания 0–180° с заданным шагом (у линии нет направления)."""
    return np.arange(0.0, 180.0, step)


def _kernel(sigma_across: float, azimuth_deg: float, order: int) -> np.ndarray:
    """Вытянутое ядро: производная гауссиана поперёк простирания.

    ``order=1`` — уступ (первая производная), ``order=2`` — долина или гребень
    (вторая производная). Сетка ядра строится в координатах массива, где
    столбец растёт на восток, а строка — на север.
    """
    s_a = float(sigma_across)
    s_l = s_a * ELONGATION
    half = int(np.ceil(3.0 * max(s_a, s_l)))
    g = np.arange(-half, half + 1, dtype=float)
    col, row = np.meshgrid(g, g)

    # Простирание: азимут от севера по часовой стрелке -> вектор (восток, север).
    a = np.deg2rad(azimuth_deg)
    e, n = np.sin(a), np.cos(a)
    along = col * e + row * n                 # координата вдоль простирания
    across = col * n - row * e                # координата поперёк

    k_along = np.exp(-0.5 * (along / s_l) ** 2)
    z = across / s_a
    if order == 1:
        k_across = -z / s_a * np.exp(-0.5 * z ** 2)
    else:
        k_across = (z * z - 1.0) / (s_a * s_a) * np.exp(-0.5 * z ** 2)
    k = k_along * k_across
    k -= k.mean()                              # нулевая сумма: плоскость -> 0
    norm = np.abs(k).sum()
    return k / norm if norm > 0 else k


def responses(dem: np.ndarray, sigma_across: float, order: int,
              step: float = AZIMUTH_STEP) -> dict[float, np.ndarray]:
    """Отклик рельефа на каждое простирание при заданной ширине ядра.

    Пропуски в рельефе заполняются медианой перед свёрткой и возвращаются как
    пропуски после неё: свёртка не умеет обрабатывать NaN, а «дыра», залитая
    нулём, сама по себе даёт ложный край.
    """
    hole = ~np.isfinite(dem)
    src = np.where(hole, np.nanmedian(dem), dem).astype(float)
    out = {}
    for az in azimuths(step):
        r = fftconvolve(src, _kernel(sigma_across, az, order), mode="same")
        r[hole] = np.nan
        out[float(az)] = r
    return out


def summarize(per_az: dict[float, np.ndarray]) -> dict[str, np.ndarray]:
    """Сводка по азимутам: сила, анизотропия и преобладающее простирание.

    Знак отклика отброшен (``abs``): линия одинаково значима, выражена ли она
    долиной или гребнем, а знак зависит от того, поднят или опущен блок.
    """
    az = np.array(sorted(per_az))
    stack = np.abs(np.stack([per_az[a] for a in az]))
    mx = np.nanmax(stack, axis=0)
    mean = np.nanmean(stack, axis=0)
    best = az[np.nanargmax(np.where(np.isfinite(stack), stack, -np.inf), axis=0)]
    ang = np.deg2rad(2.0 * best)               # удвоенный угол
    with np.errstate(invalid="ignore", divide="ignore"):
        aniso = np.where(mean > 0, (mx - mean) / mean, np.nan)
    return {"макс": mx, "анизотропия": aniso,
            "напр_sin": np.sin(ang), "напр_cos": np.cos(ang)}
