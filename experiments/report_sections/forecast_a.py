def build(deck):
    """Добавляет в `deck` слайды части A и возвращает их число."""
    start = deck.page
    for f in (s_overview, s_corpus, s_hamissana, s_nn, s_fuzzy, s_tree,
              s_elevation, s_mask, s_factors, s_sets, s_clusters, s_ladder):
        f(deck)
    added = deck.page - start
    assert added == COUNT, (added, COUNT)
    return added


