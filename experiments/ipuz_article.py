def чц(n: int) -> str:
    """Целое с неразрывным пробелом между разрядами: 22 946, а не 22946."""
    return "{:,}".format(int(n)).replace(",", " ")


def ч1(v: float) -> str:
    return ("%.1f" % v).replace(".", ",")


def ч3(v: float) -> str:
    return ("%.3f" % v).replace(".", ",")


def ч4(v: float) -> str:
    return ("%.4f" % v).replace(".", ",")


def ч6(v: float) -> str:
    return ("%.6f" % v).replace(".", ",")


