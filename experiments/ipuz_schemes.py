"""Схемы к статье «карта на знаниях»: рисуются в физическом размере полосы.

Причина переделки: схемы, подготовленные под ширину 15,5 см, при вставке на
11,5 см давали кегль внутри около 5,5 пт — на печати нечитаемо. Здесь каждая
схема строится сразу в том размере, в котором попадёт в статью (ширина
``ШИРИНА_СМ``), поэтому ``fontsize`` — это настоящие пункты на бумаге.

Запуск из корня репозитория::

    python -m experiments.ipuz_schemes
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ВЫХОД = ROOT / "outputs" / "14_статья_знания"

ШИРИНА_СМ = 11.5
ДЮЙМ = ШИРИНА_СМ / 2.54

ТЁМНЫЙ = "#1f3346"
СЕРЫЙ = "#5a6b7a"
РАМКА = "#44607a"
ЗАЛИВКА = "#eef3f7"
АКЦЕНТ = "#dbe6ef"

КЕГЛЬ_ЗАГ = 8.0
КЕГЛЬ_БОКС = 7.0
КЕГЛЬ_МЕЛК = 6.0
ПОЛЕ = 2.0


def холст(высота_дюйм: float):
    fig = plt.figure(figsize=(ДЮЙМ, высота_дюйм), dpi=400)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.axis("off")
    return fig, ax


def бокс(ax, x, y, w, h, текст, *, низ: str = "", акцент: bool = False,
         кегль: float = КЕГЛЬ_БОКС) -> None:
    ax.add_patch(FancyBboxPatch(
        (x, y), w, h, boxstyle="round,pad=0,rounding_size=1.6",
        linewidth=0.7, edgecolor=РАМКА,
        facecolor=АКЦЕНТ if акцент else ЗАЛИВКА))
    сдвиг = 3.5 if низ else 0
    ax.text(x + w / 2, y + h / 2 + сдвиг, текст, ha="center", va="center",
            fontsize=кегль, color=ТЁМНЫЙ, fontweight="bold", linespacing=1.15)
    if низ:
        ax.text(x + w / 2, y + h / 2 - 5.5, низ, ha="center", va="center",
                fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ, linespacing=1.15)


def стрелка(ax, x1, y1, x2, y2) -> None:
    ax.add_patch(FancyArrowPatch(
        (x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=7,
        linewidth=0.8, color=РАМКА, shrinkA=0, shrinkB=0))


def заголовок(ax, текст: str) -> None:
    ax.text(ПОЛЕ, 97, текст, ha="left", va="top", fontsize=КЕГЛЬ_ЗАГ,
            color=ТЁМНЫЙ, fontweight="bold")


def сноска(ax, текст: str) -> None:
    ax.text(ПОЛЕ, 3, текст, ha="left", va="bottom", fontsize=КЕГЛЬ_МЕЛК,
            color=СЕРЫЙ)


# ------------------------------------------------------------ схема 1
def схема_уровни(путь: Path) -> None:
    """Пять уровней модели и обратный проход — объяснение оценки.

    Прямой и обратный ход идут по одной и той же цепочке, поэтому они сведены
    в один рисунок: отдельная схема прослеживаемости повторяла бы те же пять
    уровней.
    """
    fig, ax = холст(1.75)
    заголовок(ax, "Пять уровней модели: расчёт вперёд, объяснение назад")
    подписи = [("Звено\nпроцесса", "путь миграции"),
               ("Объект", "разломная зона"),
               ("Критерий", "близость к зоне"),
               ("Признак", "расстояние, км"),
               ("Канал ГИС", "сетка 500 м")]
    w, h, y, шаг = 17.2, 30.0, 44.0, 19.6
    for i, (верх, низ) in enumerate(подписи):
        x = ПОЛЕ + i * шаг
        бокс(ax, x, y, w, h, верх, низ=низ, акцент=(i == 1), кегль=6.6)
        if i:
            стрелка(ax, x - (шаг - w), y + h / 2, x - 0.8, y + h / 2)
    ax.text(98, 80, "расчёт оценки ячейки →", ha="right", va="center",
            fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ)
    стрелка(ax, 96, 38, ПОЛЕ, 38)
    ax.text(ПОЛЕ, 33, "← объяснение: обратный проход к источнику "
                      "и решению эксперта",
            ha="left", va="top", fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ)
    бокс(ax, ПОЛЕ, 7, 45, 18, "Решение человека",
         низ="подтверждено · отклонено · черновик", кегль=6.2)
    бокс(ax, 53, 7, 45, 18, "Статус проверки",
         низ="проверено · опровергнуто · нет данных", кегль=6.2)
    fig.savefig(путь, facecolor="white")
    plt.close(fig)


# ------------------------------------------------------------ схема 2
def схема_выходы(путь: Path) -> None:
    """Смысл пары «оценка — обеспеченность»."""
    fig, ax = холст(1.55)
    заголовок(ax, "Два выхода метода: оценка P и обеспеченность C")
    x0, y0, w, h = 32.0, 14.0, 32.0, 28.0
    ячейки = [
        (0, 1, "P низкая, C высокая",
         "сильных свидетельств нет\nпри хороших измерениях", False),
        (1, 1, "P высокая, C высокая",
         "кандидат для проверки\nпо имеющимся данным", True),
        (0, 0, "P низкая, C низкая",
         "оснований для отрицания\nнедостаточно", False),
        (1, 0, "P высокая, C низкая",
         "содержательная гипотеза,\nнужны наблюдения", False),
    ]
    for cx, cy, верх, низ, акц in ячейки:
        бокс(ax, x0 + cx * (w + 2), y0 + cy * (h + 3), w, h, верх,
             низ=низ, акцент=акц, кегль=6.2)
    ax.text(98, 80, "обеспеченность C выше →", ha="right", va="center",
            fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ)
    ax.text(x0 - 2, y0 + h + 1.5, "оценка P выше ↑", ha="right", va="center",
            fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ)
    ax.text(ПОЛЕ, 66, "Условия наблюдения\nменяют C, но признаком\n"
                      "оруденения не являются",
            ha="left", va="top", fontsize=КЕГЛЬ_МЕЛК, color=ТЁМНЫЙ,
            linespacing=1.3)
    сноска(ax, "Схема качественная: это не результаты по территории")
    fig.savefig(путь, facecolor="white")
    plt.close(fig)


# ------------------------------------------------------------ схема 3
def схема_зависимость(путь: Path) -> None:
    """Запрет повторного счёта одного объекта."""
    fig, ax = холст(1.35)
    заголовок(ax, "Один объект — не три независимых свидетельства")
    ax.plot([50, 50], [3, 80], color="#c3ccd4", linewidth=0.7)
    ax.text(ПОЛЕ, 76, "без ограничения", fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ,
            ha="left", va="center")
    ax.text(53, 76, "с ограничением", fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ,
            ha="left", va="center")

    бокс(ax, ПОЛЕ, 24, 17, 32, "Разломная\nзона", акцент=True, кегль=6.4)
    for i, имя in enumerate(("источник", "путь", "накопление")):
        y = 48 - i * 17
        бокс(ax, 26, y, 21, 13, имя, кегль=6.2)
        стрелка(ax, ПОЛЕ + 17.6, 40, 25.4, y + 6.5)
    ax.text(ПОЛЕ, 6, "один слой засчитан трижды", fontsize=КЕГЛЬ_МЕЛК,
            color=СЕРЫЙ, ha="left", va="center")

    бокс(ax, 53, 29, 17, 24, "Разломная\nзона", акцент=True, кегль=6.4)
    бокс(ax, 74, 29, 11, 24, "не более\nодного", кегль=6.0)
    бокс(ax, 89, 29, 9, 24, "одно\nзвено", кегль=6.0)
    стрелка(ax, 70.6, 41, 73.4, 41)
    стрелка(ax, 85.6, 41, 88.4, 41)
    ax.text(53, 6, "правило применяется в каждой ячейке",
            fontsize=КЕГЛЬ_МЕЛК, color=СЕРЫЙ, ha="left", va="center")
    fig.savefig(путь, facecolor="white")
    plt.close(fig)


# ------------------------------------------------------------ схема 4
def схема_прослеживаемость(путь: Path) -> None:
    """Путь от оценки ячейки назад к источнику и решению эксперта."""
    fig, ax = холст(1.30)
    заголовок(ax, "Прослеживаемость: от оценки ячейки к источнику")
    подписи = [("Оценка\nP и C", True), ("Звено\nпроцесса", False),
               ("Критерий", False), ("Признак\nи канал", False),
               ("Источник\nи цитата", False)]
    w, h, y, шаг = 17.2, 30.0, 40.0, 19.6
    for i, (текст, акц) in enumerate(подписи):
        x = ПОЛЕ + i * шаг
        бокс(ax, x, y, w, h, текст, акцент=акц, кегль=6.6)
        if i:
            стрелка(ax, x - (шаг - w), y + h / 2, x - 0.8, y + h / 2)
    бокс(ax, ПОЛЕ, 6, 45, 23, "Решение человека",
         низ="подтверждено · отклонено · черновик", кегль=6.4)
    бокс(ax, 53, 6, 45, 23, "Статус проверки",
         низ="проверено · опровергнуто · нет данных", кегль=6.4)
    fig.savefig(путь, facecolor="white")
    plt.close(fig)


def main() -> None:
    ВЫХОД.mkdir(parents=True, exist_ok=True)
    задачи = [("схема1_уровни.png", схема_уровни),
              ("схема2_выходы.png", схема_выходы),
              ("схема3_зависимость.png", схема_зависимость),
              ("схема4_прослеживаемость.png", схема_прослеживаемость)]
    for имя, функция in задачи:
        путь = ВЫХОД / имя
        функция(путь)
        print("нарисовано:", путь.name)


if __name__ == "__main__":
    main()
