def build(deck):
    """Добавляет в `deck` слайды раздела и возвращает их число."""
    start = deck.page
    for f in (s_corpus, s_hamissana_table, s_hamissana_map, s_components,
              s_analog_maps, s_analog_check, s_shlikh,
              s_pair, s_ceiling, s_formula,
              s_transfer, s_zones,
              s_working_point, s_cores):
        f(deck)
    added = deck.page - start
    assert added == COUNT, (added, COUNT)
    return added


