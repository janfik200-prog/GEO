# --- общие помощники ---------------------------------------------------------
def _sl(deck, node_label, rubric, title, subtitle):
    return deck.slide(SEC, node_label, title, subtitle, rubric=rubric)


def kpi(deck, sl, x, y, w, h, value, label, vsize=18.0, lsize=8.0):
    """Карточка с крупным числом; цвет числа — акцент раздела."""
    rect(sl, x, y, w, h, PALE, BORDER)
    vh = vsize / 72.0 * 1.38
    tv = textbox(sl, x + 0.14, y + 0.06, w - 0.28, vh)
    run(tv.paragraphs[0], value, vsize, deck.accent, bold=True)
    top = y + 0.06 + vh + 0.03
    tl = textbox(sl, x + 0.14, top, w - 0.24, max(y + h - 0.05 - top, 0.14))
    run(tl.paragraphs[0], label, lsize, GREY)


def small(sl, x, y, w, h, text, size=7.5, italic=True, color=GREY):
    tf = textbox(sl, x, y, w, h)
    run(tf.paragraphs[0], text, size, color, italic=italic)


def pic(sl, x, y, path, w=None, h=None, caption=None, sub=None):
    """Картинка без искажения: задаётся ширина или высота."""
    with Image.open(str(path)) as im:
        ar = im.width / im.height
    if w is None:
        w = h * ar
    else:
        h = w / ar
    if y + h > 4.15:          # подпись под картинкой не должна касаться врезки
        h = 4.15 - y
        w = h * ar
    picture(sl, x, y, w, h, path, caption=caption, sub=sub)
    return w, h


