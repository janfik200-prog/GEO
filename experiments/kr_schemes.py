"""Схемы к описанию представления знаний: форма фигуры несёт смысл.

Четыре рисунка: пирамида уровней, блок-схема исполнения, три состояния и
ограничение целостности. Оформление общее — ``experiments.kr_style``.

Схемы строятся в ширине вставки (11,5 см), поэтому кегль в коде — настоящие
пункты на бумаге.

Запуск из корня репозитория::

    python -m experiments.kr_schemes
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from experiments.kr_style import (  # noqa: E402
    МЕЛК, ОСН, ТЕКСТ, выноска, карточка, многоугольник, панель,
    параллелограмм, ромб, сохранить, стрелка, трапеция, холст, шапка)

ВЫХОД = ROOT / "outputs" / "14_статья_знания"
ПУСТО = "⊥"


# ---------------------------------------------------------------- рисунок 1
def kr1(путь: Path) -> None:
    """Пирамида уровней: ширина яруса кодирует объём уровня."""
    fig, ax = холст(7.0)
    шапка(ax, "Пять уровней представления: от процесса к измерению", "синий")

    ярусы = [
        ("Звенья процесса", "5 × 4", 28.0, 36.0, "зелёный"),
        ("Геологические объекты", "20", 36.0, 44.0, "сирень"),
        ("Критерии с паспортом", "29", 44.0, 52.0, "охра"),
        ("Признаки", "240 кодов", 52.0, 60.0, "синий"),
        ("Каналы на сетке 500 м", "113 543 ячейки", 60.0, 68.0, "серый"),
    ]
    h, зазор, центр = 11.5, 1.2, 34.0
    y = 79.0
    for имя, число, wв, wн, тон in ярусы:
        y -= h
        трапеция(ax, y, h, wв, wн, имя, низ=число, тон=тон, центр_x=центр,
                 кегль=ОСН - 0.5)
        y -= зазор

    карточка(ax, 70.0, 55.0, 28.0, 19.0, "Условия\nнаблюдения",
             ["входят только в C(x)"], тон="красный", центр=True,
             кегль=ОСН - 0.6)
    карточка(ax, 70.0, 33.0, 28.0, 19.0, "Паспорт\nкритерия",
             ["направление, радиус"], тон="охра", центр=True,
             кегль=ОСН - 0.6)
    выноска(ax, 48.0, 72.0, 72.0, 87.0,
            "«играет роль» —\nмногие-ко-многим", тон="сирень")
    панель(ax, 2.0, 2.0, 96.0, 12.0, "Статусы утверждения",
           ["подтверждён · отклонён · черновик · "
            "не удаётся проверить на доступных данных"])
    сохранить(fig, путь)


