# ---------------------------------------------------------------- рисунок 3
def kr3(путь: Path) -> None:
    fig, ax = холст(5.8)
    шапка(ax, "Три состояния свидетельства и их распространение", "охра")

    состояния = [("Наблюдается", "значение в [0; 1]", "зелёный"),
                 ("%s Не наблюдается" % ПУСТО, "нет канала или условия",
                  "охра"),
                 ("Запрещено", "ячейка исключается", "красный")]
    w, h = 31.0, 16.0
    for i, (т, н, тон) in enumerate(состояния):
        карточка(ax, 2.0 + i * 32.5, 71.0, w, h, т, [н], тон=тон,
                 центр=True, кегль=ОСН - 0.3)

    цепь = [("Признак", "часть ⊥", "синий"),
            ("Критерий", "по прочим", "охра"),
            ("Объект", "по прочим", "сирень"),
            ("Звено", "все ⊥ → ⊥", "зелёный"),
            ("Итог", "выпадает", "зелёный"),
            ("C(x)", "минус 1/M", "красный")]
    w2, h2, шаг = 14.8, 16.0, 16.4
    for i, (т, н, тон) in enumerate(цепь):
        x = 1.2 + i * шаг
        карточка(ax, x, 44.0, w2, h2, т, [н], тон=тон, центр=True,
                 кегль=ОСН - 0.5)
        if i:
            стрелка(ax, x - 1.5, 52.0, x - 0.3, 52.0)

    панель(ax, 2.0, 11.0, 96.0, 23.0, "Почему не нулём и не серединой",
           ["Ноль утверждает «проверено и не выполнено» и читается",
            "как отрицание; 0,5 утверждает «известно наполовину».",
            "Отдельное состояние переносит незнание из оценки",
            "в обеспеченность — обе величины остаются содержательными."])
    сохранить(fig, путь)


# ---------------------------------------------------------------- рисунок 4
def kr4(путь: Path) -> None:
    fig, ax = холст(6.0)
    шапка(ax, "Ограничение целостности: один объект — одна роль", "жёлтый")

    карточка(ax, 2.0, 46.0, 26.0, 20.0, "Разломная зона",
             ["роли в 3 звеньях"], тон="сирень", центр=True,
             кегль=ОСН - 0.3)
    варианты = [("Вариант И", "только источник"),
                ("Вариант П", "только путь"),
                ("Вариант Н", "только накопление")]
    for i, (т, н) in enumerate(варианты):
        y = 72.0 - i * 18.0
        карточка(ax, 31.0, y, 28.0, 14.0, т, [н], тон="синий", центр=True,
                 кегль=ОСН - 0.5)
        стрелка(ax, 28.4, 56.0, 30.4, y + 7.0)
        стрелка(ax, 59.4, y + 7.0, 63.2, 56.0, стиль=(0, (4, 2)))
    ромб(ax, 81.0, 56.0, 34.0, 26.0, "Выбор\nпо ячейке:\nmax P(x)",
         тон="жёлтый", кегль=ОСН - 0.5)

    панель(ax, 2.0, 6.0, 96.0, 25.0, "Формально",
           ["Индикатор a(o, z, x) ∈ {0, 1} с ограничением Σ по z "
            "a(o, z, x) ≤ 1;",
            "выбор решается перебором допустимых назначений.",
            "Без ограничения один слой даёт три независимых свидетельства,",
            "и карта повторяет формулу, которая держится на тех же зонах."])
    сохранить(fig, путь)


def main() -> None:
    ВЫХОД.mkdir(parents=True, exist_ok=True)
    задачи = [("kr1_формализация.png", kr1), ("kr2_конвейер.png", kr2),
              ("kr3_состояния.png", kr3), ("kr4_назначение.png", kr4)]
    for имя, функция in задачи:
        функция(ВЫХОД / имя)
        print("нарисовано:", имя)


if __name__ == "__main__":
    main()
