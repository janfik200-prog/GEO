def _wide_open(zb: np.ndarray, p, q) -> np.ndarray:
    """Окно отклика с концами, выведенными из оценки (они лежат на гребнях)."""
    zz = zb.copy()
    for e in (p, q):
        zz[max(e[0] - WIDE_END_SKIP, 0):e[0] + WIDE_END_SKIP + 1,
           max(e[1] - WIDE_END_SKIP, 0):e[1] + WIDE_END_SKIP + 1] = np.inf
    return zz


def wide_bottleneck(zb: np.ndarray, p, q) -> float:
    """Слабое звено самого широкого пути p->q в окне (8-связность).

    Наибольший порог t, при котором p и q лежат в одной связной области
    {z >= t}. Ищется делением пополам по значениям окна.
    """
    from scipy.ndimage import label

    zz = _wide_open(zb, p, q)
    vals = np.unique(zz[np.isfinite(zz)])
    s8 = np.ones((3, 3), bool)
    if not len(vals):
        return float("-inf")
    lab, _ = label(zz >= vals[0], structure=s8)
    if lab[p] != lab[q]:
        return float("-inf")
    lo, hi = 0, len(vals) - 1
    while lo < hi:
        mid = (lo + hi + 1) // 2
        lab, _ = label(zz >= vals[mid], structure=s8)
        if lab[p] and lab[p] == lab[q]:
            lo = mid
        else:
            hi = mid - 1
    return float(vals[lo])


def wide_path(zb: np.ndarray, p, q, b: float) -> np.ndarray:
    """Кратчайший путь p->q внутри области z >= слабое звено."""
    from skimage.graph import route_through_array

    cost = np.where(_wide_open(zb, p, q) >= b, 1.0, 1e6)
    idx, _ = route_through_array(cost, p, q, fully_connected=True, geometric=True)
    return np.asarray(idx, dtype=int)


