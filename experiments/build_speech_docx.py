def _style(doc):
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(11)
    st.paragraph_format.space_after = Pt(8)
    st.paragraph_format.line_spacing = 1.15


def _h(doc, text, size, color=DARK, before=16, after=5):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(size)
    r.font.color.rgb = color
    return p


def build(path, title, lead, blocks, qa):
    doc = Document()
    _style(doc)
    _h(doc, title, 17, before=0, after=4)
    p = doc.add_paragraph()
    r = p.add_run(lead)
    r.italic = True
    r.font.size = Pt(10)
    r.font.color.rgb = GREY
    for head, paras in blocks:
        _h(doc, head, 12.5, ACCENT)
        for t in paras:
            doc.add_paragraph(t)
    _h(doc, "Если спросят", 13, before=20)
    for q, a in qa:
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        r = p.add_run(q + " ")
        r.bold = True
        p.add_run(a)
    doc.save(str(path))
    print(path)


