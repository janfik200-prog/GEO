"""Перестройка презентации: упор на метод, схемы шагов, итоговая карта.

Что делает прогон:

* разделяет прежний общий слайд «шаги 1–2» на два — по слайду на шаг;
* на каждый из пяти шагов ставит свою схему, построенную на реальных данных
  Анабара (``experiments.openlin_slides``);
* добавляет отдельный слайд с итоговой картой;
* оставляет заголовки и подзаголовки на местах, а содержимое под ними
  перестраивает под картинку и одну поясняющую карточку.

Стиль берётся из самой презентации: Cambria 32 для заголовков, Calibri 13–15,
тёмно-синий текст, терракотовый акцент, тёплые карточки.

Запуск из корня репозитория (после openlin_slides):
    python -m experiments.openlin_deck
"""
from __future__ import annotations

import copy
import shutil
from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN
from pptx.util import Emu, Inches, Pt

SRC = Path("presentation/Линеаменты по космоснимкам.pptx")
FIG = Path("outputs/slides")
OUTPUTS = Path("outputs")

INK = RGBColor(0x1B, 0x2A, 0x32)
INK2 = RGBColor(0x6E, 0x7F, 0x88)
ACC = RGBColor(0xC1, 0x5B, 0x33)
CARD = RGBColor(0xF4, 0xEF, 0xEA)
EDGE = RGBColor(0xD8, 0xD2, 0xC8)

W = 13.333          # ширина слайда, дюймы
TITLE_Y, SUB_Y = 0.35, 1.08


# --------------------------------------------------------------------------
# Мелкие помощники
# --------------------------------------------------------------------------

def move_slide(prs, old: int, new: int) -> None:
    """Переставить слайд: python-pptx добавляет только в конец."""
    ids = prs.slides._sldIdLst
    items = list(ids)
    ids.remove(items[old])
    ids.insert(new, items[old])


def add_slide(prs):
    return prs.slides.add_slide(prs.slide_masters[0].slide_layouts[0])


def clear(slide, keep_ids=()) -> None:
    """Убрать со слайда всё, кроме перечисленных фигур."""
    for sh in list(slide.shapes):
        if sh.shape_id not in keep_ids:
            sh._element.getparent().remove(sh._element)


def text(slide, x, y, w, h, s, size=13, color=INK, bold=False,
         align=PP_ALIGN.LEFT, font="Calibri"):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap = True
    for i, line in enumerate(s.split("\n")):
        para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        para.alignment = align
        run = para.add_run()
        run.text = line
        run.font.size = Pt(size)
        run.font.color.rgb = color
        run.font.bold = bold
        run.font.name = font
    return box


def card(slide, x, y, w, h, fill=CARD):
    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x),
                                Inches(y), Inches(w), Inches(h))
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    sh.line.color.rgb = EDGE
    sh.line.width = Pt(0.75)
    sh.shadow.inherit = False
    return sh


def head(slide, title, sub):
    """Заголовок и подзаголовок в стиле презентации."""
    text(slide, 0.6, TITLE_Y, 12.1, 0.75, title, size=32, bold=True,
         font="Cambria")
    text(slide, 0.6, SUB_Y, 12.1, 0.40, sub, size=14, color=INK2)


def picture(slide, path, y, height=None, width=None):
    """Картинка по центру слайда по горизонтали."""
    from PIL import Image

    iw, ih = Image.open(path).size
    if width is None:
        width = height * iw / ih
    if width > 12.6:
        width = 12.6
        height = width * ih / iw
    return slide.shapes.add_picture(str(path), Inches((W - width) / 2),
                                    Inches(y), Inches(width), Inches(height))


def note(slide, x, y, w, h, title, body, accent=False):
    """Карточка «заголовок + текст» — как на остальных слайдах."""
    card(slide, x, y, w, h)
    text(slide, x + 0.28, y + 0.14, w - 0.56, 0.32, title, size=15, bold=True,
         color=ACC if accent else INK)
    text(slide, x + 0.28, y + 0.52, w - 0.56, h - 0.66, body, size=12.5)


def method_slide(slide, title, sub, fig, card_title, card_body):
    """Общий шаблон слайда шага: заголовок, схема, одна карточка снизу."""
    clear(slide)
    head(slide, title, sub)
    # Высоты подобраны так, чтобы текст карточки заведомо помещался: пять строк
    # по 12.5 pt на ширине 11.6 дюйма — это около 700 знаков.
    picture(slide, FIG / fig, y=1.60, height=3.10)
    note(slide, 0.6, 4.90, 12.15, 1.72, card_title, card_body, accent=True)


# --------------------------------------------------------------------------

def main() -> None:
    backup = SRC.with_name(SRC.stem + " (до правки).pptx")
    if not backup.exists():
        shutil.copy2(SRC, backup)
        print(f"резервная копия: {backup.name}")

    prs = Presentation(str(SRC))
    s = prs.slides

    # --- слайд 4: был «шаги 1–2», становится «шаг 1» ------------------------
    method_slide(
        s[3], "Шаг 1: признаки окрестности", "10 каналов → 160: ячейка описывается "
        "устройством текстуры вокруг неё, а не своим значением", "step1.png",
        "Что считается",
        "Для каждого из 10 каналов на трёх масштабах — 500 м, 1 км, 2 км — считаются пять величин: "
        "вытянутость текстуры, её контрастность, направление (двумя числами, чтобы 5° и 185° были одним "
        "направлением) и признак «выступ или впадина». Итого 10 × 3 × 5 = 150 величин плюс 10 исходных каналов. "
        "Направления складываются через структурный тензор: иначе градиенты с двух сторон борозды "
        "гасили бы друг друга, и линия исчезала бы именно там, где она есть.")

    # --- слайд 5 (новый): шаг 2 --------------------------------------------
    n2 = add_slide(prs)
    method_slide(
        n2, "Шаг 2: сжатие 160 → 8", "Два независимых способа сжатия, и в итоговую "
        "карту идут оба", "step2.png",
        "Почему два способа, а не один",
        "Метод главных компонент строит линейные смеси признаков — линией в таком представлении становится "
        "перепад среднего. Автоэнкодер обучается восстанавливать закрытые ячейки по окрестности и кодирует "
        "ещё и смену типа текстуры при одинаковом среднем. Обучения на разметке нет ни там, ни там. "
        "Списки линий пересекаются лишь на 53–60 % длины, поэтому в карту идёт объединение: 255 линий вместо 153.")
    move_slide(prs, len(s) - 1, 4)

    # --- шаг 3 --------------------------------------------------------------
    method_slide(
        s[5], "Шаг 3: оператор границы", "Разлом или дайка — это граница между "
        "блоками с разной сигнатурой, а не гребень поля", "step3.png",
        "Что считается и почему именно так",
        "Через ячейку проводится воображаемая линия, по обе стороны от неё кладутся два окна 2 км × 200 м "
        "со сдвигом ±300 м, и считается расстояние между средними признаковыми векторами этих окон — "
        "в сигмах, то есть «на сколько типичных разбросов различаются участки». Перебираются 12 направлений, "
        "максимум даёт силу и азимут. Предыдущая версия искала гребни поля: её линии совпадали с обводкой "
        "рельефной текстуры в 1.8 раза чаще, чем с картой разломов, — гребень поля не является границей блоков.")

    # --- шаг 4 --------------------------------------------------------------
    method_slide(
        s[6], "Шаг 4: от поля силы к отрезкам", "Каждая операция снимает свой "
        "класс ложных линий", "step4.png",
        "Пять операций подряд",
        "Сглаживание убирает пиксельный шум. Подавление немаксимумов поперёк линии превращает полосу "
        "в гребень шириной в ячейку. Гистерезисный порог по двум квантилям площади сохраняет слабое "
        "продолжение сильной линии и отбрасывает слабое одиночное. Скелетизация со состриганием отростков "
        "короче 1 км не даёт одному шипу разрубить длинную линию на узле. Сшивка соединяет концы, "
        "если разрыв короче 2 км и направления расходятся не больше чем на 20°.")

    # --- шаг 5 --------------------------------------------------------------
    method_slide(
        s[7], "Шаг 5: отбор по подтверждению", "Раскол данных физический: оптика и "
        "радар обрабатываются порознь и проверяют друг друга", "step5.png",
        "Три условия отбора и цена",
        "Линия остаётся, если ОБА прибора по отдельности видят вдоль неё свою линию: не дальше 250 м, "
        "того же направления (±20°) и не меньше чем на половине длины. Требование «вдоль длины» отсекает "
        "случайные касания, требование по направлению — пересечения, которых в густой карте много. "
        "Случайный уровень меряется тороидальным сдвигом карты одного прибора: через фильтр проходит "
        "0.9 линии против 153 наблюдаемых — чистота отбора ×174.")

    # --- новый слайд: итоговая карта ---------------------------------------
    nm = add_slide(prs)
    clear(nm)
    head(nm, "Итоговая карта линеаментов Анабара",
         "255 линий, 1010 км на площадке 86 × 77 км; ожидаемое число случайных — 2")
    picture(nm, OUTPUTS / "openlin_final_anabar.png", y=1.60, height=4.35)
    text(nm, 0.6, 6.10, 12.1, 0.70,
         "Слева — карта: каждая линия подтверждена и оптикой, и радаром независимо. "
         "В центре — вклад двух способов сжатия. Справа — розы азимутов: у линеаментов преобладает "
         "северо-восточная система, у контуров зон разломов — северо-западная.",
         size=12, color=INK2)
    move_slide(prs, len(s) - 1, 9)

    prs.save(str(SRC))
    print(f"сохранено: {SRC}, слайдов стало {len(prs.slides)}")


if __name__ == "__main__":
    main()
