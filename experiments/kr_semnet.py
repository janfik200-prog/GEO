ПОЛОСЫ = [(87.0, "Выходы ячейки"), (34.0, "")]
ПОДПИСЬ_НИЗА = "Слой данных: признаки и каналы"

СМЕЩЕНИЕ = {"лево": (-1.0, 0.0, "right", "center"),
            "право": (1.0, 0.0, "left", "center"),
            "верх": (0.0, 1.0, "center", "bottom"),
            "низ": (0.0, -1.0, "center", "top")}


def край(узел: str, к: str) -> tuple[float, float]:
    """Точка на границе кружка в направлении другого узла."""
    x1, y1 = УЗЛЫ[узел][0], УЗЛЫ[узел][1]
    x2, y2 = УЗЛЫ[к][0], УЗЛЫ[к][1]
    dx, dy = x2 - x1, y2 - y1
    д = (dx ** 2 + dy ** 2) ** 0.5 or 1.0
    return x1 + dx / д * РАД_X * 1.15, y1 + dy / д * РАД_Y * 1.15


def main() -> None:
    fig = plt.figure(figsize=(Ш_ДЮЙМ, В_ДЮЙМ), dpi=DPI)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.axis("off")
    fig.patch.set_facecolor("white")

    for y, подпись in ПОЛОСЫ:
        ax.plot([1, 99], [y, y], color="#9aa7b0", linewidth=0.8,
                linestyle=(0, (2, 3)), zorder=1)
        if подпись:
            ax.text(1, y - 1.2, подпись, ha="left", va="top",
                    fontsize=КЕГЛЬ_ПОЛОСЫ, color=СЕРЫЙ, style="italic")
    ax.text(0.8, 35.6, "знания ↑", ha="left", rotation=90,
            va="bottom", fontsize=КЕГЛЬ_ПОЛОСЫ, color=СЕРЫЙ, style="italic")
    ax.text(0.8, 32.4, "данные ↓", ha="left", rotation=90, va="top",
            fontsize=КЕГЛЬ_ПОЛОСЫ, color=СЕРЫЙ, style="italic")

    for a, b, подпись, стиль, толщина, цвет, сдвиг in РЁБРА:
        x1, y1 = край(a, b)
        x2, y2 = край(b, a)
        ax.add_patch(FancyArrowPatch(
            (x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=7,
            linewidth=толщина, color=цвет, linestyle=стиль,
            shrinkA=0, shrinkB=0, zorder=2))
        if подпись:
            ax.text((x1 + x2) / 2 + сдвиг, (y1 + y2) / 2, подпись,
                    ha="center", va="center", fontsize=КЕГЛЬ_РЕБРА,
                    color=цвет, zorder=4, style="italic",
                    bbox=dict(boxstyle="round,pad=0.12", fc="white",
                              ec="none", alpha=0.92))

    for x, y, подпись, сторона, заливка in УЗЛЫ.values():
        ax.add_patch(Ellipse((x, y), РАД_X * 2, РАД_Y * 2, linewidth=1.1,
                             edgecolor=ЛИНИЯ, facecolor=заливка, zorder=5))
        dx, dy, ha, va = СМЕЩЕНИЕ[сторона]
        ax.text(x + dx * (РАД_X + 1.1), y + dy * (РАД_Y + 1.1), подпись,
                ha=ha, va=va, fontsize=КЕГЛЬ_УЗЛА, color=ТЁМНЫЙ,
                fontweight="bold", zorder=6, linespacing=1.2)

    ax.text(1, 99, "Семантическая сеть представления знаний", ha="left",
            va="top", fontsize=9.5, color=ТЁМНЫЙ, fontweight="bold")
