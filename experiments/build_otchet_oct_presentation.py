def _area():
    """Общая подложка: координаты ячеек, маска области, зона «лист»."""
    d = pd.read_parquet(config.PROCESSED_DIR / "terrain_drift_maps.parquet")
    x, y = d["x"].to_numpy(float), d["y"].to_numpy(float)
    common = d["в_области"].to_numpy(bool)
    ext = (x.min() - 250, x.max() + 250, y.min() - 250, y.max() + 250)
    sheet = common & (zone_of(x, y) == "лист")
    return d, x, y, common, sheet, ext, (ARCH_META.prf, ARCH_META.pic)


def _frame(ax, x, y, sheet, ext):
    """Единое оформление панели: рамка листа, пределы, подписи осей."""
    sx, sy = x[sheet], y[sheet]
    ax.add_patch(Rectangle((sx.min() - 250, sy.min() - 250),
                           sx.max() - sx.min() + 500,
                           sy.max() - sy.min() + 500,
                           fill=False, ec="#1E293B", lw=0.8, ls="--"))
    ax.set_xlim(ext[0], ext[1])
    ax.set_ylim(ext[2], ext[3])
    ax.set_aspect("equal")
    ax.set_xticks([500000, 550000, 600000])
    ax.xaxis.set_major_formatter(lambda v, _: "%.0f" % (v / 1000))
    ax.yaxis.set_major_formatter(lambda v, _: "%.0f" % (v / 1000))
    ax.set_xlabel("X, км")


def fig_terrain_drift(path):
    """Две панели переноса: вариант A (как есть) и принятый вариант C.

    Источник — data/processed/terrain_drift_maps.parquet, сохранённый
    прогоном experiments/terrain_drift_fix.py.
    """
    d, x, y, common, sheet, ext, shape = _area()
    cmap = ListedColormap(["#DCE3EC", "#A3122B"])
    plt.rcParams.update({"font.size": 7.5})
    fig, axes = plt.subplots(1, 2, figsize=(4.20, 2.95),
                             constrained_layout=True)
    panels = (("A: как есть", "A · как есть"),
              ("C: рельеф по зонам", "C · рельеф по зонам (принят)"))
    for ax, (col, ttl) in zip(axes, panels):
        v = d[col].to_numpy(float)
        img = np.full(x.size, np.nan)
        img[common] = 0.0
        img[common & (v >= np.nanquantile(v[common], 0.9))] = 1.0
        ax.imshow(np.ma.masked_invalid(img.reshape(shape)), extent=ext,
                  origin="upper", interpolation="nearest", vmin=0, vmax=1,
                  cmap=cmap)
        ax.set_title(ttl, fontsize=8)
        _frame(ax, x, y, sheet, ext)
    axes[0].set_ylabel("Y, км")
    axes[1].set_yticklabels([])
    fig.savefig(path, dpi=250)
    plt.close(fig)


def fig_uranium(path):
    """Урановый прогноз Госгеолкарты и наш прогноз на одной площади.

    Источники — outputs/12_внешние_данные/урановые_зоны_контуры.csv,
    data/processed/sw_shlikh_points.csv, terrain_drift_maps.parquet
    (вариант C). Повторяет experiments/uranium_vs_ours.py в размере слайда.
    """
    d, x, y, common, sheet, ext, shape = _area()
    ours = d["C: рельеф по зонам"].to_numpy(float)

    z = pd.read_csv(EXT_DIR / "урановые_зоны_контуры.csv")
    zones = {}
    for tag, pair in (("6.1 Западно-Анабарская", (1, 2)),
                      ("6.1.1/6.1.2", (1, 3))):
        g = z[z["зона"] == tag]
        a = g[g["линия"] == pair[0]][["X_м", "Y_м"]].to_numpy()
        b = g[g["линия"] == pair[1]][["X_м", "Y_м"]].to_numpy()
        poly = MplPath(np.vstack([a, b[::-1], a[:1]]))
        zones[tag] = (poly.contains_points(np.column_stack([x, y])),
                      [g[g["линия"] == k][["X_м", "Y_м"]].to_numpy()
                       for k in sorted(g["линия"].unique())])

    tr = Transformer.from_crs("EPSG:4326", CRS.from_proj4(PROJ4),
                              always_xy=True)
    sh = pd.read_csv(config.PROCESSED_DIR / "sw_shlikh_points.csv", sep=";")
    sx, sy = tr.transform(sh["долгота"].to_numpy(), sh["широта"].to_numpy())

    plt.rcParams.update({"font.size": 7.5})
    fig, axes = plt.subplots(1, 2, figsize=(4.20, 2.95),
                             constrained_layout=True)
    img = np.where(common, 0.0, np.nan)
    img[zones["6.1 Западно-Анабарская"][0] & common] = 1.0
    img[zones["6.1.1/6.1.2"][0] & common] = 2.0
    axes[0].imshow(np.ma.masked_invalid(img.reshape(shape)), extent=ext,
                   origin="upper", interpolation="nearest", vmin=-0.5,
                   vmax=2.5,
                   cmap=ListedColormap(["#EEEEF2", "#CFE3C8", "#7FB069"]))
    axes[0].set_title("Урановый прогноз\nГосгеолкарты, лист R-48", fontsize=8)

    cuts = np.nanpercentile(ours[common], mapstyle.CLASS_EDGES[1:-1])
    cls = np.where(common, np.digitize(ours, cuts).astype(float), np.nan)
    axes[1].imshow(np.ma.masked_invalid(cls.reshape(shape)), extent=ext,
                   origin="upper", interpolation="nearest", vmin=-0.5,
                   vmax=4.5, cmap=ListedColormap(mapstyle.CLASS_COLORS))
    axes[1].set_title("Наш прогноз,\nтекущая версия", fontsize=8)
    for p in zones["6.1 Западно-Анабарская"][1]:
        axes[1].plot(p[:, 0], p[:, 1], color="#1A7F3C", lw=0.9, ls=(0, (6, 2)))

    for ax in axes:
        ax.scatter(sx, sy, s=14, marker="*", c="#101010", zorder=6)
        _frame(ax, x, y, sheet, ext)
    axes[0].set_ylabel("Y, км")
    axes[1].set_yticklabels([])
    fig.savefig(path, dpi=250)
    plt.close(fig)


