def build_halves(site: str, log, channel: str = "B04") -> dict[str, np.ndarray]:
    """Две половины зимнего композита для подтверждения, канал shade.

    Делятся СЦЕНЫ, не лист: каждая половина покрывает лист целиком. Внутри
    каждой плитки сцены по дате раздаются через одну (1-я и 3-я — в «А», 2-я —
    в «Б»), так что обе половины получают сцены всех четырёх плиток (покрытие
    100 %; деление по сезону давало 22.8 %, по датам на весь набор — 11.4 %).
    ИЗВЕСТНАЯ АСИММЕТРИЯ: при трёх сценах на плитку деление 2 + 1, в «А» восемь
    сцен, в «Б» четыре; на 77 % листа ячейка «Б» — одна сцена без медианы, и
    подтверждение упирается именно в неё. Перестановкой тех же двенадцати сцен
    это не лечится, только чётным числом сцен на плитку.
    """
    from experiments.openlin_winter import _ndvi, detrend, normalize

    out = {}
    files = sorted(CACHE.glob("*_лист_20m.npz"),
                   key=lambda f: f.name.split("_")[2][:8])
    by_tile: dict[str, list] = {}
    for f in files:
        tile = next(p for p in f.name.split("_") if p.startswith("T"))
        by_tile.setdefault(tile, []).append(f)
    halves = {"А": [], "Б": []}
    for tile, group in sorted(by_tile.items()):
        halves["А"] += group[0::2]
        halves["Б"] += group[1::2]
    log("  сцен по плиткам: " + ", ".join(f"{t} {len(g)}"
                                          for t, g in sorted(by_tile.items())))
    for name, group in halves.items():
        suffix = "" if channel == "B04" else f"_{channel}"
        p = COMP / f"winter_{site}_20m_лист_{name}{suffix}.npz"
        if p.exists():
            out[name] = np.load(p)["shade"]
            log(f"  половина «{name}» — из кэша")
            continue
        layers = []
        for f in group:
            if channel == "ndvi":
                # NDVI сцены — по сырым яркостям, как в полном композите
                layers.append(_ndvi(dict(np.load(f))))
                continue
            b = np.load(f)["B04"].astype("float32")
            good = np.isfinite(b) & (b > 0)
            layers.append(normalize(b, good))
        cube = np.stack(layers)
        n = np.isfinite(cube).sum(0)
        with np.errstate(invalid="ignore"):
            med = np.nanmedian(cube, axis=0)
        med = np.where(n >= HALF_MIN_SCENES, med, np.nan).astype("float32")
        valid = np.isfinite(med)
        sh = detrend(med, valid, 20.0)
        np.savez_compressed(p, shade=sh, count=n.astype("int16"))
        out[name] = sh
        log(f"  половина «{name}»: сцен {len(layers)} "
            f"({', '.join(f.name.split('_')[2][:8] for f in group)}), "
            f"ячеек с медианой {100 * valid.mean():.1f} %")
    return out


def pair_geometry(lines: list, zone, strike, res_m: float) -> np.ndarray:
    """Разрыв вдоль простирания и боковой сдвиг для пар соосных обрывков."""
    from scipy.spatial import cKDTree

    from experiments.openlin_lines import _axis

    cand = []
    for r in lines:
        p = r["pts"]
        st = _line_strike(p, strike)
        if zone[p[:, 0], p[:, 1]].mean() >= ZONE_FRAC and \
                _adiff(r["азимут"], st) <= DIR_TOL_DEG:
            _ax, a, b = _axis(p)
            cand.append((a.astype(float), b.astype(float), st))
    if len(cand) < 2:
        return np.zeros((0, 2))
    E = np.array([e for c in cand for e in c[:2]])
    own = np.repeat(np.arange(len(cand)), 2)
    out = []
    for i, j in cKDTree(E).query_pairs(PAIR_MAX_M / res_m):
        if own[i] == own[j]:
            continue
        st = cand[own[i]][2]
        a = np.radians(st)
        u = np.array([-np.cos(a), np.sin(a)])       # вдоль простирания (row, col)
        n = np.array([np.sin(a), np.cos(a)])        # поперёк
        v = E[j] - E[i]
        out.append((abs(v @ u) * res_m, abs(v @ n) * res_m))
    return np.array(out)


def extend_ends(lines, z, valid, res_m: float, log=None) -> list:
    """Продолжение линий за концы по их же направлению («память направления»).

    Ход идёт от конца линии её собственным направлением, отклик берётся тем же
    способом, что и в замере (:func:`openlin_trace_extend.walk`: максимум из
    трёх ячеек — на оси хода и по одной вбок), усредняется по отрезку
    ``EXT_SEG_M`` и сравнивается с нижним порогом гистерезиса ЭТОГО отклика.
    Продолжение обрывается на первом отрезке ниже порога и в любом случае не
    длиннее ``EXT_MAX_M``.
    """
    from skimage.draw import line as draw_line

    from experiments.openlin_iso import Q_LOW, _describe
    from experiments.openlin_lines import _axis
    from experiments.openlin_trace_extend import walk

    if not lines:
        return lines
    thr = float(np.quantile(z[valid], Q_LOW))
    t_max = int(EXT_MAX_M / res_m)
    W = max(int(EXT_SEG_M / res_m), 1)
    ends, dirs, own = [], [], []
    for i, r in enumerate(lines):
        # продолжаются только линии от MIN_LEN_M — та же совокупность, на
        # которой сделан замер; у обрывка в пару ячеек направление не
        # определено, и ход на 900 м был бы не продолжением, а выдумкой
        if r["длина_км"] * 1000 < MIN_LEN_M:
            continue
        ax, e1, e2 = _axis(r["pts"])
        u = np.asarray(ax, dtype="float64")
        u = u / max(float(np.hypot(*u)), 1e-9)
        mid = r["pts"].mean(0)
        for e in (e1, e2):
            sgn = np.sign((np.asarray(e, dtype="float64") - mid) @ u) or 1.0
            ends.append(np.asarray(e, dtype="float64"))
            dirs.append(u * sgn)
            own.append(i)
    ends, dirs = np.asarray(ends), np.asarray(dirs)
    prof = walk(np.where(valid, z, np.nan).astype("float32"), valid, ends,
                dirs, res_m, t_max)
    seg = np.nanmean(np.lib.stride_tricks.sliding_window_view(prof, W, axis=1),
                     axis=2)
    ok = np.nan_to_num(seg, nan=-9.0) > thr
    grow = {}
    for i in range(len(ends)):
        j = 0
        while j < ok.shape[1] and ok[i, j]:
            j += 1
        if j:
            e = ends[i] + dirs[i] * j
            rr, cc = draw_line(int(round(ends[i][0])), int(round(ends[i][1])),
                               int(round(e[0])), int(round(e[1])))
            inb = ((rr >= 0) & (rr < valid.shape[0])
                   & (cc >= 0) & (cc < valid.shape[1]))
            rr, cc = rr[inb], cc[inb]
            if not len(rr):
                continue
            keep = valid[rr, cc]
            grow.setdefault(own[i], []).append(
                np.stack([rr[keep], cc[keep]], 1))
    out, added = [], 0
    for i, r in enumerate(lines):
        if i not in grow:
            out.append(r)
            continue
        pts = np.unique(np.concatenate([r["pts"]] + grow[i]), axis=0)
        d = _describe(pts, res_m)
        if d is None:
            out.append(r)
            continue
        ax, _a, _b = _axis(pts)
        d["азимут"] = float(np.degrees(np.arctan2(ax[1], -ax[0])) % 180.0)
        added += d["длина_км"] - r["длина_км"]
        out.append(d)
    if log is not None:
        log(f"  продолжено концов {sum(len(v) for v in grow.values())} у "
            f"{len(grow)} линий из {len(lines)}, прибавка {added:.0f} км "
            f"(порог {thr:.3f}, отрезок {EXT_SEG_M:.0f} м, предел "
            f"{EXT_MAX_M:.0f} м)")
    return out


def conf_share(lines, dts) -> tuple[float, int]:
    """Доля линий, подтверждённых ОБЕИМИ половинами (и их число)."""
    ok = sum(1 for r in lines
             if all((d[r["pts"][:, 0], r["pts"][:, 1]] <= CONF_TOL_M).mean()
                    >= CONF_FRAC for d in dts))
    return ok / max(len(lines), 1), ok


def shift_null_conf(lines, dts, shape, log=None,
                    n_shifts: int | None = None) -> tuple[float, float]:
    """Сдвиговый нуль для этапа подтверждения: доля случайных совпадений и p.

    Половины остаются настоящими — со всей структурой и со всей связью между
    собой; по тору сдвигаются линии, то есть рушатся только МЕСТА. Сдвигаются
    именно точки линий, а не карты расстояний: это то же самое с точностью до
    знака сдвига, но не требует копировать два больших массива 200 раз.
    """
    H, W = shape
    n_sh = SHIFT_N if n_shifts is None else int(n_shifts)
    rng = np.random.default_rng(SHIFT_SEED)
    obs = conf_share(lines, dts)[0]
    out = []
    for _ in range(n_sh):
        lo_r, lo_c = min(200, H // 8), min(200, W // 8)   # поля, чтобы сдвиг был настоящим
        dr = int(rng.integers(lo_r, H - lo_r))
        dc = int(rng.integers(lo_c, W - lo_c))
        moved = [{"pts": np.stack([(r["pts"][:, 0] + dr) % H,
                                   (r["pts"][:, 1] + dc) % W], 1)}
                 for r in lines]
        out.append(conf_share(moved, dts)[0])
    out = np.array(out)
    pval = float((1 + (out >= obs).sum()) / (1 + n_sh))
    if log is not None:
        log(f"сдвиговый нуль подтверждения ({n_sh} сдвигов): доля "
            f"{100 * out.mean():.1f} % (макс {100 * out.max():.0f} %) против "
            f"{100 * obs:.0f} % на месте, p = {pval:.3f} "
            f"(пол достижимого {1 / (1 + n_sh):.4f})")
    return float(out.mean()), pval


def close_along_strike(zone, strike, res_m: float, log=None) -> np.ndarray:
    """Замыкание зоны отрезком ``V4_CLOSE_M`` вдоль местного простирания.

    Направление меняется по листу, поэтому одно замыкание не годится: поле
    простирания режется на ``V4_CLOSE_BINS`` секторов, для каждого зона
    замыкается отрезком своего наклона, и добавленные ячейки берутся только
    там, где СОБСТВЕННОЕ простирание ячейки попадает в этот сектор. Так
    смыкаются пятна одной полосы, а разнонаправленные пятна не слипаются.
    """
    from scipy.ndimage import binary_closing

    step = 180.0 / V4_CLOSE_BINS
    half = V4_CLOSE_M / (2.0 * res_m)
    out = zone.copy()
    for b in range(V4_CLOSE_BINS):
        az = (b + 0.5) * step
        t = np.linspace(-half, half, int(2 * half) + 1)
        rr = np.round(-np.cos(np.radians(az)) * t).astype(int)
        cc = np.round(np.sin(np.radians(az)) * t).astype(int)
        se = np.zeros((rr.max() - rr.min() + 1, cc.max() - cc.min() + 1), dtype=bool)
        se[rr - rr.min(), cc - cc.min()] = True
        sector = np.abs(((strike - az + 90.0) % 180.0) - 90.0) <= step / 2.0
        out |= binary_closing(zone, se) & sector
    if log is not None:
        log(f"замыкание зоны вдоль простирания ({V4_CLOSE_M:.0f} м, "
            f"{V4_CLOSE_BINS} секторов): доля листа "
            f"{100 * zone.mean():.1f} % -> {100 * out.mean():.1f} %")
    return out


def link_same_side(lines, zone, strike, res_m, log=None, z=None,
                   support: str = "mean", offset_m: float | None = None) -> list:
    """Сшивка обрывков по всему листу, с опорой мостика на отклик.

    Условия пары: собственные азимуты обрывков расходятся не больше
    ``DIR_TOL_DEG``; разрыв вдоль их общего направления <= ``V5_GAP_M``, сдвиг
    вбок <= ``V4_OFFSET_M``; проекции на это направление не перекрываются
    (иначе это две параллельные линии, а не одна разорванная); сдвиги внутри
    цепочки — в одну сторону; и мостик ОПИРАЕТСЯ НА ОТКЛИК: его средний отклик
    выше ``V7_BRIDGE_Q``-го процентиля нуля, посчитанного переносом тех же
    мостиков в случайные места этого же снимка.

    ``zone`` и ``strike`` больше не ограничивают сшивку (см. LINK_MIN_LEN_M в
    шапке) и оставлены в сигнатуре ради вызовов старых прогонов.
    """
    from scipy.spatial import cKDTree
    from skimage.draw import line as draw_line

    from experiments.openlin_iso import _describe
    from experiments.openlin_lines import _axis

    cand, rest = [], []
    for r in lines:
        if r["длина_км"] * 1000 >= LINK_MIN_LEN_M:
            r["_st"] = r["азимут"]
            cand.append(r)
        else:
            rest.append(r)
    if len(cand) < 2:
        return lines
    ends, own = [], []
    for i, r in enumerate(cand):
        _ax, a, b = _axis(r["pts"])
        ends += [a, b]
        own += [i, i]
    E = np.asarray(ends, dtype="float64")
    off_max = V4_OFFSET_M if offset_m is None else float(offset_m)
    rad = np.hypot(V5_GAP_M, off_max) / res_m
    pairs = []
    for p_, q_ in cKDTree(E).query_pairs(rad):
        i, j = own[p_], own[q_]
        if i == j:
            continue
        v = E[q_] - E[p_]
        if np.hypot(*v) < 1:
            continue
        if _adiff(cand[i]["_st"], cand[j]["_st"]) > DIR_TOL_DEG:
            continue
        # среднее направление — по удвоенным углам, иначе 175 и 5 дали бы 90
        t = np.radians(2 * np.array([cand[i]["_st"], cand[j]["_st"]]))
        st = (np.degrees(np.arctan2(np.sin(t).mean(), np.cos(t).mean())) / 2) % 180.0
        a = np.radians(st)
        u = np.array([-np.cos(a), np.sin(a)])       # вдоль простирания (строка, столбец)
        n = np.array([np.sin(a), np.cos(a)])        # поперёк
        along, across = abs(v @ u) * res_m, (v @ n) * res_m
        if along > V5_GAP_M or abs(across) > off_max:
            continue
        # обрывки одной линии идут ДРУГ ЗА ДРУГОМ: их проекции на простирание
        # не перекрываются. Перекрытие означает две параллельные линии рядом
        ti, tj = cand[i]["pts"] @ u, cand[j]["pts"] @ u
        if (min(ti.max(), tj.max()) - max(ti.min(), tj.min())) * res_m \
                > V6_OVERLAP_MAX_M:
            continue
        pairs.append((float(np.hypot(*v)), p_, q_,
                      0 if abs(across) < V4_SIDE_MIN_M else int(np.sign(across))))
    # опора мостика: средний отклик по его ВНУТРЕННИМ ячейкам против нуля из
    # тех же мостиков, перенесённых по тору (концы мостика лежат на гребнях и
    # завысили бы оценку, поэтому по две ячейки с каждой стороны отбрасываются)
    wpath = {}
    if z is not None and pairs and support == "wide":
        # опора по самому широкому пути (см. WIDE_* в шапке)
        H, W = z.shape
        m = max(int(round(CONF_TOL_M / res_m)), 1)
        zf = np.where(np.isfinite(z), z, -np.inf).astype("float32")
        boxes, keep_idx = [], []
        for k, (_d, p_, q_, _sg) in enumerate(pairs):
            p = (int(E[p_][0]), int(E[p_][1])); q = (int(E[q_][0]), int(E[q_][1]))
            if max(abs(p[0] - q[0]), abs(p[1] - q[1])) < 2 * WIDE_END_SKIP + 1:
                keep_idx.append(k); continue        # внутренних ячеек нет
            r0, c0 = min(p[0], q[0]) - m, min(p[1], q[1]) - m
            ri = np.arange(r0, max(p[0], q[0]) + m + 1)
            ci = np.arange(c0, max(p[1], q[1]) + m + 1)
            boxes.append((k, ri, ci, (p[0] - r0, p[1] - c0), (q[0] - r0, q[1] - c0)))
        vals = np.array([wide_bottleneck(zf[np.ix_(ri % H, ci % W)], pl, ql)
                         for _k, ri, ci, pl, ql in boxes])
        rng = np.random.default_rng(31)
        null = []
        for _ in range(V7_BRIDGE_SHIFTS):
            dr = int(rng.integers(200, H - 200)); dc = int(rng.integers(200, W - 200))
            for _k, ri, ci, pl, ql in boxes:
                zs = zf[np.ix_((ri + dr) % H, (ci + dc) % W)]
                if np.isfinite(zs).all():           # коридор целиком в данных
                    null.append(wide_bottleneck(zs, pl, ql))
        thr = float(np.quantile(np.array(null), V7_BRIDGE_Q))
        for (k, ri, ci, pl, ql), v in zip(boxes, vals):
            if v > thr:
                keep_idx.append(k)
                pt = wide_path(zf[np.ix_(ri % H, ci % W)], pl, ql, v) \
                    + np.array([ri[0], ci[0]])
                pt = pt[(pt[:, 0] >= 0) & (pt[:, 0] < H) & (pt[:, 1] >= 0) & (pt[:, 1] < W)]
                wpath[(pairs[k][1], pairs[k][2])] = pt
        n_all = len(pairs)
        pairs = [pairs[k] for k in sorted(set(keep_idx))]
        if log is not None:
            log(f"  опора мостика (путь): порог слабого звена {thr:.3f} "
                f"({100 * V7_BRIDGE_Q:.0f} % нуля), прошло {len(pairs)} пар из {n_all}")
    elif z is not None and pairs:
        H, W = z.shape
        tracks, keep_idx = [], []
        for k, (_d, p_, q_, _sg) in enumerate(pairs):
            rr, cc = draw_line(int(E[p_][0]), int(E[p_][1]),
                               int(E[q_][0]), int(E[q_][1]))
            if len(rr) < 5:
                keep_idx.append(k); continue
            tracks.append((k, rr[2:-2], cc[2:-2]))
        vals = np.array([np.nanmean(z[rr, cc]) for _k, rr, cc in tracks])
        rng = np.random.default_rng(31)
        null = []
        for _ in range(V7_BRIDGE_SHIFTS):
            dr = int(rng.integers(200, H - 200)); dc = int(rng.integers(200, W - 200))
            null += [np.nanmean(z[(rr + dr) % H, (cc + dc) % W])
                     for _k, rr, cc in tracks]
        thr = float(np.nanquantile(np.array(null), V7_BRIDGE_Q))
        keep_idx += [k for (k, _rr, _cc), v in zip(tracks, vals) if v > thr]
        pairs = [pairs[k] for k in sorted(set(keep_idx))]
        if log is not None:
            log(f"  опора мостика: порог {thr:.3f} ({100 * V7_BRIDGE_Q:.0f} % "
                f"нуля), прошло {len(pairs)} пар из {len(tracks)}")
    pairs.sort(key=lambda x: x[0])
    parent = list(range(len(cand)))
    side = [0] * len(cand)

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    used = np.zeros(len(E), dtype=bool)
    bridges, kulisa, joined = {}, {}, 0
    for _d, p_, q_, sg in pairs:
        if used[p_] or used[q_]:
            continue
        ra, rb = find(own[p_]), find(own[q_])
        if ra == rb:
            continue
        if sg and side[ra] and side[ra] != sg:
            continue                                # сдвиг в другую сторону
        if sg and side[rb] and side[rb] != sg:
            continue
        used[p_] = used[q_] = True
        parent[rb] = ra
        side[ra] = side[ra] or side[rb] or sg
        joined += 1
        if (p_, q_) in wpath:                       # мостик по найденному пути
            rr, cc = wpath[(p_, q_)][:, 0], wpath[(p_, q_)][:, 1]
        else:
            rr, cc = draw_line(int(E[p_][0]), int(E[p_][1]),
                               int(E[q_][0]), int(E[q_][1]))
        bridges.setdefault(own[p_], []).append(np.stack([rr, cc], 1))
        if sg:          # сдвиг вбок не меньше V4_SIDE_MIN_M: мостик через кулису
            kulisa.setdefault(own[p_], []).append(np.stack([rr[1:-1], cc[1:-1]], 1))
    groups, gkul = {}, {}
    for i, r in enumerate(cand):
        groups.setdefault(find(i), []).append(r["pts"])
        groups[find(i)].extend(bridges.get(i, []))
        gkul.setdefault(find(i), []).extend(kulisa.get(i, []))
    out = list(rest)
    for gid, g in groups.items():
        pts = np.unique(np.concatenate(g), axis=0)
        d = _describe(pts, res_m)
        if d is None:
            continue
        ax, _a, _b = _axis(pts)
        d["азимут"] = float(np.degrees(np.arctan2(ax[1], -ax[0])) % 180.0)
        # ячейки мостиков через кулисы — дорисованные, не найденные: линия
        # считается одной цепочкой, но рисовать и подтверждать их не обязательно
        d["кулисы"] = (np.concatenate(gkul[gid]) if gkul.get(gid)
                       else np.zeros((0, 2), dtype=int))
        out.append(d)
    if log is not None:
        log(f"  сшито стыков {joined}: обрывков от {LINK_MIN_LEN_M:.0f} м "
            f"{len(cand)}, пар после опоры {len(pairs)}, линий после сшивки "
            f"{len(out)}")
    return out


def drop_seam_lines(lines, seam, res_m: float, log=None) -> list:
    """Выбрасывает линии, идущие ВДОЛЬ шва съёмки (но не пересекающие его)."""
    from scipy.ndimage import distance_transform_edt
    from scipy.spatial import cKDTree

    if not seam.any() or not lines:
        return lines
    ds = distance_transform_edt(~seam, sampling=(res_m, res_m))
    S = np.argwhere(seam).astype(float)
    tree = cKDTree(S)
    out, dropped = [], 0
    for r in lines:
        p = r["pts"]
        near = ds[p[:, 0], p[:, 1]] <= SEAM_NEAR_M
        if near.mean() < SEAM_FRAC:
            out.append(r); continue
        idx = tree.query_ball_point(p.mean(0), r=SEAM_NEAR_M / res_m + 10)
        if len(idx) < 10:
            out.append(r); continue
        q = S[idx] - S[idx].mean(0)
        vt = np.linalg.svd(q, full_matrices=False)[2]
        az = float(np.degrees(np.arctan2(vt[0][1], -vt[0][0])) % 180.0)
        if _adiff(r["азимут"], az) <= DIR_TOL_DEG:
            dropped += 1
            continue
        out.append(r)
    if log is not None:
        log(f"  отсев вдоль швов съёмки: убрано {dropped} линий из {len(lines)}")
    return out


def select2(lines, zone, strike, dts, gate: bool = True) -> tuple[list, list]:
    """Набор А и набор В (А + подтверждение обеими половинами).

    ``gate`` — прежний фильтр «не меньше половины длины в зоне согласия и вдоль
    её простирания». С 23.09.2026 он выключаем, и вот почему. Поэтапный замер
    показал, что этот этап отсеивает ПОДДЕЛКУ ХУЖЕ, чем снимок (отношение 1.86
    против 1.0 у нейтрального этапа), то есть шума он не убирает. А глазная
    проверка показала, чего он стоит: в контрольном окне 6 трассировка нашла 11
    линий длиннее 500 м, часть подтверждена обеими съёмками на 100 %, и все они
    выброшены — у них 0 % длины внутри пятен зоны при 31 % зоны в окне.
    Поэтому зона переводится из ФИЛЬТРА в ПРИЗНАК: набор считается и с ней, и
    без неё, обе версии проходят одни и те же четыре проверки.
    """
    A, C = [], []
    for r in lines:
        p = r["pts"]
        if gate:
            if zone[p[:, 0], p[:, 1]].mean() < ZONE_FRAC:
                continue
            st = _line_strike(p, strike)
            if _adiff(r["азимут"], st) > DIR_TOL_DEG:
                continue
        A.append(r)
        if all((d[p[:, 0], p[:, 1]] <= CONF_TOL_M).mean() >= CONF_FRAC for d in dts):
            C.append(r)
    return A, C


