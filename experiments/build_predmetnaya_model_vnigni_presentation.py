_TOKEN = re.compile(r"(\*\*.+?\*\*|`.+?`)")


def runs(p, line, size, color, bold=False, italic=False):
    """Строка с разметкой: **жирное**, `код` (моноширинный)."""
    for part in _TOKEN.split(line):
        if not part:
            continue
        b, font = bold, None
        if part.startswith("**"):
            part, b = part[2:-2], True
        elif part.startswith("`"):
            part, font = part[1:-1], MONO
        r = p.add_run()
        set_run(r, part, size, color, bold=b, italic=italic)
        if font:
            r.font.name = font


def text(s, x, y, w, h, paras, size=11, color=DARK, anchor=MSO_ANCHOR.TOP,
         align=PP_ALIGN.LEFT, space=2, spacing=1.0, inset=0.06, bold=False,
         italic=False):
    """Надпись из абзацев; абзац — строка или (строка, кегль, цвет)."""
    tf = textbox(s, I(x), I(y), I(w), I(h), anchor)
    tf.margin_left = tf.margin_right = I(inset)
    tf.margin_top = tf.margin_bottom = I(0.03)
    for i, para in enumerate(paras):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.space_after = Pt(space)
        p.line_spacing = spacing
        if isinstance(para, tuple):
            line, sz, col = para
        else:
            line, sz, col = para, size, color
        runs(p, line, sz, col, bold=bold, italic=italic)
    return tf


def box(s, x, y, w, h, fill, paras, size=11, color=DARK, border=None,
        dash=False, bw=1.25, anchor=MSO_ANCHOR.MIDDLE, align=PP_ALIGN.CENTER,
        radius=0.08, rounded=True, inset=0.06, spacing=1.0, bold=False,
        italic=False):
    """Плашка (заливка, рамка по желанию) с текстом внутри."""
    if rounded:
        sp = round_rect(s, I(x), I(y), I(w), I(h), fill or WHITE, radius)
    else:
        sp = rect(s, I(x), I(y), I(w), I(h), fill or WHITE)
    if fill is None:
        sp.fill.background()
    if border is not None:
        sp.line.color.rgb = border
        sp.line.width = Pt(bw)
        if dash:
            sp.line.dash_style = MSO_LINE_DASH_STYLE.DASH
    if paras:
        text(s, x, y, w, h, paras, size, color, anchor, align, inset=inset,
             spacing=spacing, bold=bold, italic=italic)
    return sp


def line(s, x1, y1, x2, y2, color=GREY, weight=1.25, arrow=True, dash=False,
         elbow=False):
    """Прямая (или ломаная) стрелка в дюймах; `dash` — пунктир."""
    if elbow:
        cxn = connector(s, I(x1), I(y1), I(x2), I(y2), color, weight, arrow)
    else:
        cxn = s.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, I(x1), I(y1),
                                     I(x2), I(y2))
        cxn.line.color.rgb = color
        cxn.line.width = Pt(weight)
        if arrow:
            ln = cxn.line._get_or_add_ln()
            ln.append(ln.makeelement(
                "{http://schemas.openxmlformats.org/drawingml/2006/main}"
                "tailEnd", {"type": "triangle", "w": "med", "len": "med"}))
    if dash:
        cxn.line.dash_style = MSO_LINE_DASH_STYLE.DASH
    return cxn


