"""Пункт 2 «мутного стекла»: тот же контраст коридоров на снимках других сезонов.

ОТКУДА ВОПРОС. Обнаружимость есть произведение двух сомножителей: насколько
хорошо детектор ищет и насколько сильно объект проявлен. Первый сомножитель
выжат: шаг 0 дал порог 1.48 sigma, накопление вдоль линии опустило его до 0.60,
и там оно упёрлось в геометрию — чтобы дотянуть до реального контраста коридоров
0.194 sigma, нужен прямолинейный разлом около 95 км, а поперечник листа 77 км.
Значит остаётся второй сомножитель, и этот прогон меряет только его.

ВОПРОС, ОДНОЙ СТРОКОЙ: контраст коридоров на зимних и весенних снимках — это те
же 0.086-0.194 sigma, что летом, или больше?

ПОЧЕМУ СЕЗОН. Все композиты проекта — медианы за июль-август, снимки сплошной
травы (98.3% пикселей листа). Всё, что живёт неделями и связано с водой, такая
медиана стирает по построению. В мерзлоте разлом проявляется именно так: зона
трещиноватости проницаема, по ней разгружаются подземные воды, зимой они
намерзают наледями, весной там иначе лежит и сходит снег.

ПОЧЕМУ РАДАР ОСНОВНОЙ, А ОПТИКА ТОЛЬКО ОДНИМ ОКНОМ. Оба оптических конвейера
проекта бракуют снег по построению (S2: класс 11 не в ``S2_SCL_KEEP``; Landsat:
бит 5 в ``L8_QA_REJECT_BITS``), и на 71 градусе с.ш. это выбрасывает февраль-май
целиком. Sentinel-1 RTC не зависит ни от освещения, ни от облаков. Landsat
участвует только в весеннем окне и только с ослабленной маской
(``config.SEA_L8_QA_REJECT_BITS``, снег сохранён); Sentinel-2 не участвует —
его маска классовая, одним параметром не ослабляется, и это ограничение
инструмента, а не вывод о сенсоре.

ЭТО ОПИСАНИЕ, А НЕ ПРОВЕРКА ГИПОТЕЗЫ. Ни одного p-value, ни одной alpha,
знаменатель Бонферрони НЕ РАСТЁТ — ровно как у шага 0, где карта разломов тоже
использовалась описательно. Сдвиговая планка нужна как ШКАЛА: у широкого коридора
против кольца контраст не нулевой сам по себе, и без неё число «0.3 sigma» нечем
прочитать. Называть сравнение с этой шкалой тестом нельзя. Если по итогам ветку
захочется продолжить гипотезой, она обязана объявить своё слагаемое в ledger ДО
прогона.

СОСТАВ ЗАФИКСИРОВАН ДО ПРОГОНА в ``config.SEA_CANDIDATES`` — шесть строк
(сенсор, поле, окно), первой стоит летняя планка тем же кодом на том же сенсоре,
чтобы сезонные числа сравнивались с ней напрямую, а не с числом из шага 0,
полученным на другом окне месяцев.

Выход: ``outputs/metrics/seasonal_contrast.csv``,
``outputs/seasonal_contrast.png``.
Запуск из корня: ``python -m experiments.seasonal_contrast_run``
(``--only s1`` — ограничить сенсор; ``--shifts N`` — размер шкалы).

РЕЗУЛЬТАТ (прогон 28.08.2026, все 16 строк, 4 окна x 2 сенсора x 2 системы).

ОТВЕТ ОТРИЦАТЕЛЬНЫЙ, И ОН СИЛЬНЕЕ ОЖИДАВШЕГОСЯ: сезон не просто не помогает —
ЛУЧШИМ ОКНОМ ОСТАЛОСЬ ЛЕТО. Контраст по системе СЗ (Sentinel-1, доли sigma):

* лето     0.243   (шкала сдвигов q95 0.313)
* наледи   0.231   (0.289)
* ледостав 0.231   (0.317)
* зима     0.213   (0.274)

По системе СВ сезонные окна проваливаются в ноль: 0.016 / 0.025 / 0.010 против
летних 0.110. Оптика в весеннем окне ведёт себя так же: ``l8/red`` 0.141 / 0.019
против летних 0.083 / 0.087, а ``l8/ndwi`` даёт 0.003 / 0.016 при sigma самого
композита 0.005 — весенний NDWI листа почти однороден, то есть искомого «лёд
против тундры» на коридорах не возникает вовсе.

ГЛАВНОЕ ЧИСЛО: НИ ОДНА ИЗ 16 СТРОК НЕ ВЫХОДИТ ЗА СВОЮ ШКАЛУ СДВИГОВ. Наибольшее
отношение контраста к q95 — 0.80 (наледи, СЗ). То есть в любом сезоне и на любом
сенсоре коридор разломов даёт на снимке не больше того, что даёт коридор той же
формы, положенный на тот же снимок куда попало. Оговорка обязательна и здесь:
шкала — единица измерения, а не тест; p-value ветка не считает, знаменатель
Бонферрони не вырос.

ЧТО ЭТО ЗНАЧИТ ДЛЯ «МУТНОГО СТЕКЛА». Второй сомножитель выжат так же, как первый.
Порог обнаружения после накопления вдоль линии — 0.60 sigma, лучший сезонный
контраст — 0.243 sigma, не хватает 2.5 раза. Гипотеза о наледях и разгрузке
подземных вод проверена прямо и не подтвердилась: если сигнал такого рода на
листе и есть, он не превышает изменчивости самого снимка. Ветка закрывается тем
же образом, что и предыдущие: не «не нашли», а «измерили, насколько не хватает».

СВЕРКА С ШАГОМ 0 СОШЛАСЬ. ``l8/red лето`` даёт 0.083 против 0.086 у шага 0 — при
ДРУГОЙ маске качества (снег сохранён) и другой квоте сцен. Прибор меряет то же
самое, что и калибровка шага 0, поэтому сезонные числа с летними сравнимы.

ЧЕГО СТОИЛА ИНФРАСТРУКТУРА (три отказа, все закрыты кодом и тестами):

* витрина Sentinel-1 RTC в Planetary Computer деградировала 26-28.08.2026 —
  сцена читалась 150-400 с вместо 14-19 с. Лечится не ожиданием: чтение сцен
  распараллелено (``config.SEA_READ_WORKERS``), окно из 76 сцен вместо 3.4 часов
  занимает ~25 минут;
* поиск в каталоге простоял 15 минут без байта и без исключения — у клиента
  pystac не было таймаута вообще, и повторы в ``search`` не могли сработать
  (``config.SAT_STAC_TIMEOUT_S``);
* прогон ``--only l8`` вынес вердикт всей ветки по одной оптике, пройдя проверку
  на основное окно: окно-то посчиталось, но сенсором, который зиму и ледостав не
  видит по построению. Отсюда вторая проверка — на основной сенсор
  (``config.SEA_PRIMARY_SENSOR``).
"""
import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from src import (cell_mask, config, detection_limit as dl,  # noqa: E402
                 integro_grid, seasonal_contrast as sea)

#: Колонка расстояния до коридора каждой системы — те же, что в шаге 0.
TARGETS: dict[str, str] = {"СЗ (tect1)": "dist_tect1", "СВ (tect2)": "dist_tect2"}

#: Контраст летних композитов, измеренный шагом 0 (система СЗ, максимум по
#: источникам) — то, с чем сравнивается результат.
STEP0_SUMMER: dict[str, float] = {"s2": 0.194, "s1": 0.188, "psr": 0.147, "l8": 0.086}

#: Порог обнаружения после накопления вдоль линии, лучшее по всей таблице.
ACC_BEST_LIMIT: float = 0.60


def _log_factory(t0):
    def log(msg=""):
        print(f"[{time.time() - t0:5.0f}s] {msg}", flush=True)
    return log


def _one(kind, field, window, meta, df, pool, n_shifts, log):
    """Одна строка пре-регистрированного списка: композит -> контраст -> шкала."""
    items = sea.window_items(kind, meta, window)
    years = sorted({i.datetime.year for i in items})
    log(f"  сцен {len(items)}, годы {years}")
    if len(items) < config.SEA_MIN_ITEMS:
        log(f"  меньше {config.SEA_MIN_ITEMS} сцен — строка пропущена")
        return []

    img, res_m, failed = sea.window_field(kind, field, meta, items)
    cover = float(np.isfinite(img).mean())
    sigma = dl.robust_sigma(img)
    log(f"  композит {img.shape}, валидных пикселей {cover:.1%}, "
        f"sigma (MAD*1.4826) = {sigma:.4g}")
    if failed:
        log(f"  битых сцен пропущено: {failed} из {len(items)} — "
            "композит собран по остальным")
    if cover < 0.5 or not np.isfinite(sigma) or sigma <= 0:
        log("  покрытие или sigma не позволяют мерить — строка пропущена")
        return []

    values = sea.cells_from_image(img, meta, res_m, pool)
    rows = []
    for name, col in TARGETS.items():
        if col not in df.columns:
            log(f"  нет колонки {col} — «{name}» пропущена")
            continue
        dist = df[col].to_numpy(dtype=float)
        got = dl.corridor_contrast(values, dist, sigma)
        ref = sea.shift_reference(values, dist, sigma, meta, n_shifts=n_shifts)
        rows.append({
            "сенсор": kind, "поле": field, "окно": window, "система": name,
            "сцен": len(items), "битых_сцен": failed,
            "покрытие": cover, "sigma": sigma,
            "контраст_медиан": got["contrast_median"],
            "контраст_разброса": got["contrast_spread"],
            "шкала_медиана": float(np.nanmedian(ref)),
            "шкала_q95": float(np.nanquantile(ref, 0.95)),
            "шкала_max": float(np.nanmax(ref)),
            "ячеек_внутри": got["n_inside"], "ячеек_в_кольце": got["n_ring"],
        })
        log(f"  {name}: контраст {got['contrast_median']:.3f} sigma "
            f"(шкала сдвигов: медиана {np.nanmedian(ref):.3f}, "
            f"q95 {np.nanquantile(ref, 0.95):.3f})")
    return rows


def _plot(res: pd.DataFrame, out_png: Path, log) -> None:
    """Контраст по окнам против летней планки и против порога обнаружения."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    if res.empty:
        log("нечего рисовать")
        return
    systems = list(dict.fromkeys(res["система"]))
    fig, axes = plt.subplots(1, len(systems), squeeze=False,
                             figsize=(6.2 * len(systems), 4.2), sharey=True)
    for j, syst in enumerate(systems):
        ax = axes[0][j]
        sub = res[res["система"] == syst].reset_index(drop=True)
        x = np.arange(len(sub))
        ax.bar(x, sub["контраст_медиан"], 0.62, color="#2d6a9f",
               label="контраст коридора")
        # Шкала сдвигов рисуется отрезком, а не полосой: это единица измерения,
        # а не порог принятия решения, и полоса читалась бы как критерий.
        ax.plot(x, sub["шкала_q95"], "_", ms=22, mew=2.2, color="#c9541b",
                label="шкала сдвигов, q95")
        ax.axhline(ACC_BEST_LIMIT, color="crimson", ls="--", lw=1.3,
                   label=f"порог обнаружения {ACC_BEST_LIMIT}")
        ax.set_xticks(x)
        ax.set_xticklabels([f"{r['сенсор']}/{r['поле']}\n{r['окно']}"
                            for _, r in sub.iterrows()], fontsize=8)
        ax.set_title(syst, fontsize=10)
        ax.grid(axis="y", alpha=0.3)
        if j == 0:
            ax.set_ylabel("контраст коридора, доли sigma снимка")
    axes[0][-1].legend(fontsize=8)
    fig.suptitle("Контраст коридоров карты разломов по сезонам\n"
                 "красная штриховая — куда надо дотянуть, чтобы разлом стал видимым",
                 fontsize=11)
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=120, bbox_inches="tight")
    plt.close(fig)
    log(f"карта: {out_png}")


def _report(res: pd.DataFrame) -> None:
    print(f"\n{'=' * 92}\nСЕЗОННЫЙ КОНТРАСТ КОРИДОРОВ (доли sigma снимка)\n{'=' * 92}")
    if res.empty:
        print("Ни одна строка не посчиталась.")
        return
    print(f"\n{'сенсор':<7}{'поле':<7}{'окно':<10}{'система':<13}{'сцен':>6}"
          f"{'покрытие':>10}{'контраст':>10}{'шкала q95':>11}{'отношение':>11}")
    for _, r in res.iterrows():
        ratio = (r["контраст_медиан"] / r["шкала_q95"]
                 if r["шкала_q95"] > 0 else np.nan)
        print(f"{r['сенсор']:<7}{r['поле']:<7}{r['окно']:<10}{r['система']:<13}"
              f"{r['сцен']:>6.0f}{r['покрытие']:>10.1%}"
              f"{r['контраст_медиан']:>10.3f}{r['шкала_q95']:>11.3f}{ratio:>11.2f}")

    print("\nШкала сдвигов — ЕДИНИЦА ИЗМЕРЕНИЯ, а не порог принятия решения:\n"
          "p-value в этой ветке не считается, знаменатель Бонферрони не растёт.")

    # ВЕРДИКТ НЕ ВЫНОСИТСЯ, ПОКА НЕ ПОСЧИТАНО ОСНОВНОЕ ОКНО. Регрессия на прогон
    # 26.08.2026: три сезонных окна упали на таймаутах каталога, посчиталась одна
    # летняя планка — и скрипт бодро напечатал «смена сезона разломы видимыми не
    # делает», хотя ни одного несезонного окна в таблице не было. Отрицательный
    # вывод, полученный из отсутствия данных, хуже отсутствия вывода.
    got_windows = set(res["окно"])
    missing = [w for w in config.SEA_WINDOWS if w not in got_windows]
    if config.SEA_PRIMARY not in got_windows:
        print(f"\nВЫВОД НЕ ФОРМУЛИРУЕТСЯ: основное окно «{config.SEA_PRIMARY}» не "
              f"посчиталось.\nНе хватает окон: {', '.join(missing)}. "
              "Ветка отвечает на вопрос «отличается ли\nсезон от лета», и без "
              "сезона в таблице любой вывод был бы про пустое место.")
        return
    # ТА ЖЕ ОШИБКА ПО ДРУГОЙ ОСИ. Прогон 28.08.2026 с `--only l8` посчитал окно
    # «наледи» по Landsat, проверку выше прошёл — и напечатал вердикт всей ветки
    # по одной оптике. Но зиму и ледостав оптика не видит в принципе (снег), так
    # что основной сенсор здесь радар, и без него вывод опирается на сенсор,
    # заведомо слепой к двум окнам из четырёх.
    primary_rows = res[res["сенсор"] == config.SEA_PRIMARY_SENSOR]
    if config.SEA_PRIMARY not in set(primary_rows["окно"]):
        print(f"\nВЫВОД НЕ ФОРМУЛИРУЕТСЯ: основное окно «{config.SEA_PRIMARY}» "
              f"посчиталось, но не на основном сенсоре «{config.SEA_PRIMARY_SENSOR}».\n"
              "Оптика бракует снег по построению и зиму с ледоставом не видит; "
              "вывод\nо всей ветке по ней одной был бы выводом по слепому прибору.\n"
              "Таблица выше — законный результат, вывод ветки — нет.")
        return
    if missing:
        print(f"\nОГОВОРКА: не посчитаны окна {', '.join(missing)} — "
              "сравнение неполное.")

    best = res.loc[res["контраст_медиан"].idxmax()]
    summer = res[res["окно"] == "лето"]["контраст_медиан"]
    print(f"\nЛучший контраст: {best['контраст_медиан']:.3f} sigma "
          f"({best['сенсор']}/{best['поле']}, окно {best['окно']}, {best['система']}).")
    if len(summer):
        base = float(summer.max())
        print(f"Летняя планка тем же кодом: {base:.3f} sigma "
              f"-> отношение {best['контраст_медиан'] / base:.2f}.")
    print(f"Порог обнаружения после накопления вдоль линии: {ACC_BEST_LIMIT} sigma.")
    if best["контраст_медиан"] >= ACC_BEST_LIMIT:
        print("ВЫВОД: сезонный контраст ДОТЯГИВАЕТ до порога обнаружения — разломы\n"
              "на таких снимках должны быть видимы, и ветку надо открывать заново\n"
              "уже гипотезой, с пре-регистрацией своего слагаемого в ledger.")
    else:
        need = ACC_BEST_LIMIT / best["контраст_медиан"]
        print(f"ВЫВОД: до порога обнаружения не хватает ещё {need:.1f} раза.\n"
              "Смена сезона сама по себе разломы видимыми не делает.")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--only", default="", help="ограничить сенсор (s1 или l8)")
    ap.add_argument("--shifts", type=int, default=config.SEA_N_SHIFTS,
                    help="размер сдвиговой шкалы")
    args = ap.parse_args()

    t0 = time.time()
    log = _log_factory(t0)

    meta = integro_grid.read_pgrid(config.GOLD_TARGET_PGRID)
    df = pd.read_parquet(sorted(config.PROCESSED_DIR.glob("dataset_v*.parquet"))[-1])
    pool = np.where(cell_mask.build_valid_mask(df))[0]
    log(f"сетка {meta.prf}x{meta.pic}, валидных ячеек {pool.size}")
    windows = ", ".join(f"{k} {v}" for k, v in config.SEA_WINDOWS.items())
    log(f"окна: {windows}; основное «{config.SEA_PRIMARY}»")
    log("знаменатель Бонферрони НЕ увеличивается: ветка описательная, "
        "p-value против карты разломов не считается")

    out_dir = ROOT / "outputs" / "metrics"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_csv = out_dir / "seasonal_contrast.csv"

    rows: list[dict] = []
    for kind, field, window in config.SEA_CANDIDATES:
        if args.only and kind != args.only:
            continue
        log(f"--- {kind}/{field}, окно «{window}» "
            f"(месяцы {sea.window_months(window)}) ---")
        try:
            rows += _one(kind, field, window, meta, df, pool, args.shifts, log)
        except Exception as exc:                     # noqa: BLE001
            # Сетевой сбой на одной строке не должен ронять весь прогон: строка
            # помечается пропущенной и это видно в итоговой таблице.
            log(f"  строка пропущена по ошибке: {type(exc).__name__}: {exc}")
        # Таблица переписывается ПОСЛЕ КАЖДОЙ строки, а не в конце. ИЗМЕРЕНО
        # 26.08.2026: каталог лёг на середине прогона, и при записи в конце
        # пропало бы и то окно, которое успело посчитаться, — вместе с часом
        # скачивания. Строка стоит десятков минут, запись — миллисекунд.
        if rows:
            pd.DataFrame(rows).to_csv(out_csv, index=False, encoding="utf-8-sig")

    if not rows:
        log("ни одна строка не посчиталась")
        return
    res = pd.DataFrame(rows)
    log(f"сохранено: {out_csv}")

    _report(res)
    _plot(res, ROOT / "outputs" / "seasonal_contrast.png", log)


if __name__ == "__main__":
    main()
