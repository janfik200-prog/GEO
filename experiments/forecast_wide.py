"""Продакшн-модель на всём листе и её применение к смежной территории.

Обучение идёт на всей территории основного листа сразу (решение 20.08.2026:
ветка leave-one-object-out закрыта) — это не валидация, а получение единственной
прод-модели для скоринга сетки, на которой критериальный расчёт не проводился
(нет `prognoz`, нет способа проверить обобщение честно).

Разметка (решение 01.09.2026): позитивы — top-`config.CREF_AREA` (10%)
критериального прогноза как отдельные ячейки-точки, БЕЗ группировки в связные
компоненты-«объекты» и без пространственного буфера. Раньше позитивами были
385 ячеек трёх крупнейших компонент при абсолютном пороге 0.15; это расходилось
с эталоном согласия (`crit_reference`, `compare_methods`, `atypicality_*`),
который всегда мерялся по top-10%, в 5.2 раза — три перспективные зоны крупнее
20 ячеек не содержали ни одного обучающего позитива. Теперь мишень обучения и
эталон оценки — одно определение.

Оговорка о переносе: прогноз на смежной территории остаётся экстраполяцией.
Критериальный `prognoz` за пределами основного листа не вычисляется (факторные
слои формулы ограничены его контуром), поэтому там нет ни мишени, ни
независимой заверки — карту следует читать как «где признаки похожи на
критериально перспективные площади листа», а не как проверенный прогноз.
Новое с 02.09.2026: сама способность набора работать вдали от обучения теперь
измерена на разрыве 15 км (см. ниже), так что перенос перестал быть проверкой
на веру — но 15 км и полторы сотни километров до смежного листа всё же разные
расстояния, и оговорка остаётся в силе.

Признаки — набор с ИЗМЕРЕННОЙ переносимостью (58 столбцов,
`data/processed/honest_feature_set.json`, 02.09.2026): группы `s2 s2raw l8 s1
ter relief2 lin dist`. Это главное изменение по сравнению с прежней версией,
и вот почему оно понадобилось.

Перенос на смежную территорию — это по определению прогноз далеко от обучения,
а до 02.09.2026 никто не проверял, работает ли модель на таком расстоянии.
Проверка (полосы + разрыв 15 км между обучением и тестом,
`experiments/honest_feature_signal.py`) показала, что прежний набор из 105
признаков на таком разрыве даёт ROC-AUC 0.421 — хуже случайного, то есть
перенос давал бы не слабый прогноз, а систематически перевёрнутый. Причина
адресная: группа `gm` (гравика) объясняется координатами на 87% и на отложенной
полосе даёт 0.320, группа `pf` — 0.460. Бустинг выбирает такой признак как
удобную замену координатам; на своей территории это работает, за её пределами
региональный тренд другой, и знак предсказания меняется. Локальная аномалия
(признак минус сглаженное поле 20 км) их не спасает — 0.361.

Что осталось и что выброшено:

* `gm`, `pf` — выброшены как непереносимые (не как геологически неважные).
* `ast`, `opt`, `psr` — не обыграли даже голые координаты на разрыве.
* `ls` — по-прежнему выброшена по покрытию: только северная полоса широкой
  сетки, на юге почти сплошной NaN.
* `*_n_obs`, `*_valid_frac` — служебные столбцы съёмки. Проверены отдельно
  (`honest_feature_service_check.py`): сами по себе дают ROC-AUC 0.734, и весь
  вклад приходится на `n_obs` (0.738) — геометрию витков спутника, тогда как
  `valid_frac` не даёт ничего (0.506). Полосы витков протяжённые и с резкими
  границами, поэтому переносятся не хуже геологии; на широкой сетке они будут
  совершенно другими, и модель, опирающаяся на них, перенеслась бы вхолостую.

Измеренная переносимость этого набора: ROC-AUC 0.753 против 0.663 у гладкого
пространственного поля (64 гауссовых базиса, модель знает только «где» и ни
одного признака) и 0.5 у случайного. Собственный вклад признаков сверх
географии — +0.090.

Здесь обучение идёт НЕ на всех 58, а на 37 (`honest_features("перенос")`):
убраны группы `l8`, `s1` и `dist`. Ни одна из трёх не выброшена за слабость —
причина в том, что на смежной территории они означают не то же, что на листе.

* `l8`, `s1` — покрытие. На основном листе `s1` не пропущен нигде, `l8` в
  0.25% ячеек; на широкой сетке `l8` есть лишь у 61.9% ячеек, `s1` у 72.2%,
  обе съёмки сразу — у 61.5%. Гистограммный бустинг выучивает правило «куда
  отправлять пропуск» по пропускам обучающей выборки; здесь их почти нет,
  значит правило не выучено, и на трети смежной территории 19 признаков ушли
  бы в произвольную ветку. Измерено (`honest_coverage_variants.py`, тот же
  протокол полос с разрывом 15 км): наивный перенос полной модели в ячейки
  без этих съёмок даёт 0.7086, а модель, честно обученная без них, — 0.7518,
  столько же, сколько полная (0.7527). Радар без потери убирается и на самом
  листе (0.7624 без `s1`).
* `dist` — смысл признака за контуром листа. Гидросеть (`dnl.shp`,
  `dnara.shp`) оцифрована только в пределах листа, поэтому за его границей
  «расстояние до реки» превращается в расстояние до края оцифровки: 72% и 68%
  ячеек широкой сетки лежат вне обучающего диапазона (до 106 и 112 км против
  5.6 и 14 км на обучении). Это тот же сорт дефекта, что и `*_n_obs`, —
  признак кодирует не геологию, а положение относительно данных. Цена отказа
  ничтожна: 0.7483 против 0.7518, при том что сами дистанции дают 0.6036 —
  ниже географической планки 0.6625.

Поэтому вся широкая сетка кроется ОДНОЙ моделью на признаках, определённых
одинаково по обе стороны границы листа, а не мозаикой моделей по зонам данных.

Все цифры переносимости выше считаны одиночным `HistGradientBoostingClassifier`
(он на порядок быстрее и годится для сравнения наборов между собой), а карты
строит `HistBackgroundEnsemble`. Расхождение проверено отдельно
(`honest_model_form.py`, тот же протокол полос): ансамбль даёт +0.0003 на 58
признаках и +0.0019 на 37 при разбросе по фолдам ±0.08-0.09, то есть схема
усреднения по фону здесь не решает ничего — приведённые цифры характеризуют и
прод-модель тоже. Подвыборка фона вводилась под прежнюю разметку в 385
позитивов (фон подавлял их в 50 раз); при нынешних 2295 против 20651 (1:9)
она стала лишней работой, но не вредной, поэтому оставлена как есть.

МАСКА ОБНАЖЁННОСТИ (07.09.2026). Спектральные признаки Sentinel-2 подаются в
модель только в тех ячейках, где есть открытый грунт; в остальных ставится
пропуск, плюс добавляется признак-флаг «спектр измерен»
(`src/spectral_mask.py`). Причина: индекс, посчитанный под растительностью,
описывает не породу, а ландшафт, и модель на нём учится. Замер по протоколу
полос: совпадение с критериальным прогнозом без тренда 0.279 при спектрах
везде против 0.362 с маской. Маска считается одинаково по обе стороны границы
листа: открытый грунт есть у 34.8% ячеек листа и 29.9% ячеек широкой сетки,
так что признак определён на смежной территории не хуже, чем на обучающей.

Пропуски в модель передаются как есть: базовый алгоритм —
`HistBackgroundEnsemble` (гистограммный бустинг), он учит направление ветвления
для NaN. Прежний `BackgroundEnsemble` (RF+GB) требовал `fillna(0)`, а для
отражательных индексов ноль — не нейтральное значение, а край шкалы: на границе
покрытия ASTER это давало контраст, неотличимый от геологического.

Модель здесь ОТДЕЛЬНАЯ от `dataset_v5_rebuilt`-прогонов задачи 3 (другой набор
признаков и другой алгоритм) — сравнивать её метрики с ними напрямую нельзя.

Выход: `data/processed/forecast_wide.parquet` (row/col/x/y/score),
`outputs/forecast_wide_map.png`.

Запуск из корня репозитория: ``python -m experiments.forecast_wide``.
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import config, criterial_target, features_v2, spectral_mask  # noqa: E402
from src.model import HistBackgroundEnsemble  # noqa: E402
from experiments.fetch_wide_area import WIDE_META  # noqa: E402

DROP_GROUPS = ("ls",)
# Из группы `ast` оставляем только признаки с измеренной положительной важностью
# (feature_relevance_ast_v6.csv), остальные 24 дропаются — см. докстринг.
AST_KEEP = ("ast_kaolin", "ast_b04")


def _keep(col: str) -> bool:
    """Набор-кандидат (105 признаков), от которого шёл отбор по переносимости.

    Оставлен как есть: на нём считаны `honest_feature_signal.py` и
    `honest_feature_selection.py`, и менять его задним числом — значит
    обнулить их результаты. Обучение берёт не его, а `honest_features()`.
    """
    group = features_v2.feature_group(col)
    if group in DROP_GROUPS:
        return False
    if group == "ast":
        return col in AST_KEEP
    return True


def honest_features(kind: str = "основной") -> list[str]:
    """Признаки, переносимость которых измерена (см. докстринг модуля).

    ``kind="основной"`` — 58 столбцов для основного листа со сплошным
    покрытием; ``kind="перенос"`` — 39 столбцов без групп `l8` и `s1`, которых
    на смежной территории нет более чем в трети ячеек.
    """
    spec = json.loads((config.PROCESSED_DIR / "honest_feature_set.json")
                      .read_text(encoding="utf-8"))
    key = {"основной": "признаки", "перенос": "признаки_перенос"}[kind]
    return list(spec[key])


def main() -> None:
    # Не через criterial_target.build_dataset: он делает fillna(0), а нам нужны
    # NaN как есть — гистограммный бустинг обрабатывает их сам.
    feat_df = criterial_target.training_features("v5_rebuilt")
    base_names = [c for c in honest_features("перенос") if c in feat_df.columns]
    # Спектры — только там, где видна порода (см. докстринг, маска обнажённости).
    feat_df = spectral_mask.apply(feat_df[base_names])
    feat_names = list(feat_df.columns)
    X = feat_df.to_numpy(dtype=float)
    n_nan_cols = int((~np.isfinite(X)).any(axis=0).sum())
    print(f"Обучающих признаков: {len(feat_names)} (набор для переноса, без l8/s1 — "
          f"см. докстринг); с пропусками на листе: {n_nan_cols}")
    keep = spectral_mask.exposure_mask(feat_df)
    print(f"Спектр измерен на листе: {int(keep.sum())} ячеек ({keep.mean():.1%})")

    # Разметка (решение 01.09.2026): top-CREF_AREA критериального прогноза, то же
    # определение, по которому меряется согласие методов. Ни группировки в связные
    # компоненты-«объекты», ни пространственного буфера — LOO закрыт 20.08.2026.
    _, prognoz = criterial_target.load_prognoz_grid()
    if len(feat_df) != prognoz.size:
        raise ValueError(f"признаки {len(feat_df)} ячеек != сетка prognoz {prognoz.size}")
    pos_mask = criterial_target.training_positives(prognoz)
    pos_idx = np.flatnonzero(pos_mask)
    # Фон — ВСЕ непозитивные ячейки, без подвыборки: прежний CRIT_N_BACKGROUND=2000
    # подбирался под 385 позитивов (1:5.2); при 2295 позитивах те же 2000 дали бы
    # 53% позитивов в обучении — вырожденный баланс для схемы «объект/фон».
    # Прореживание фона и так делает сам ансамбль (ENS_BG_FRAC на каждом раунде).
    bg_idx = np.flatnonzero(~pos_mask)
    train_idx = np.concatenate([pos_idx, bg_idx])
    y = np.concatenate([np.ones(len(pos_idx)), np.zeros(len(bg_idx))]).astype(int)
    print(f"Обучение: {len(pos_idx)} позитивов (top-{config.CREF_AREA:.0%}), "
          f"{len(bg_idx)} фона, доля позитивов {100 * len(pos_idx) / len(train_idx):.1f}%")

    model = HistBackgroundEnsemble(random_state=config.CRIT_SEED)
    model.fit(X[train_idx], y)

    # У гистограммного бустинга нет feature_importances_ — считаем важность по
    # перестановкам на подвыборке обучения (это важность in-sample, ориентир для
    # чтения карты, а не оценка обобщения).
    from sklearn.inspection import permutation_importance
    rng = np.random.default_rng(config.CRIT_SEED)
    sub = rng.choice(len(train_idx), size=min(4000, len(train_idx)), replace=False)
    perm = permutation_importance(model, X[train_idx[sub]], y[sub],
                                  n_repeats=3, random_state=config.CRIT_SEED,
                                  scoring="roc_auc", n_jobs=1)
    imp = pd.Series(perm.importances_mean, index=feat_names).sort_values(ascending=False)
    print("Топ-10 признаков по важности (перестановки, in-sample):")
    print(imp.head(10).to_string())

    wide = pd.read_parquet(config.PROCESSED_DIR / "dataset_wide.parquet")
    missing = [c for c in base_names if c not in wide.columns]
    if missing:
        raise RuntimeError(f"нет в dataset_wide.parquet: {missing}")
    # Без fillna: пропуски идут в модель как пропуски (см. докстринг).
    wide_feat = spectral_mask.apply(wide[base_names])
    keep_wide = spectral_mask.exposure_mask(wide_feat)
    print(f"Спектр измерен на широкой сетке: {int(keep_wide.sum())} ячеек "
          f"({keep_wide.mean():.1%})")
    X_wide = wide_feat[feat_names].to_numpy(dtype=float)
    score = model.predict_proba(X_wide)[:, 1]

    out = wide[["row", "col", "x", "y"]].copy()
    out["score"] = score.astype(np.float32)
    out_path = config.PROCESSED_DIR / "forecast_wide.parquet"
    out.to_parquet(out_path, index=False)
    print(f"OK: {out_path} {out.shape}")

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    grid = score.reshape(WIDE_META.shape)
    fig, ax = plt.subplots(figsize=(9, 9.5))  # сетка почти квадратная: 151 x 150 км
    im = ax.imshow(grid, origin="upper", cmap="viridis",
                    extent=[WIDE_META.x0, WIDE_META.x0 + WIDE_META.pic * WIDE_META.dx,
                            WIDE_META.y0, WIDE_META.y_top])
    ax.set_title(f"Прогноз модели: обучение на верхних {config.CREF_AREA:.0%} критериального\n"
                  f"прогноза основного листа ({len(pos_idx)} ячеек), {len(feat_names)} признаков\n"
                  "со сплошным покрытием обеих территорий; спектры — только на обнажённых\n"
                  "смежная территория — экстраполяция, критериального расчёта там нет")
    ax.set_xlabel("X, м")
    ax.set_ylabel("Y, м")
    fig.colorbar(im, ax=ax, label="score (вероятность класса «объект»)", fraction=0.03)
    fig.tight_layout()
    fig_path = config.PROJECT_ROOT / "outputs" / "forecast_wide_map.png"
    fig.savefig(fig_path, dpi=130)
    print(f"OK: {fig_path}")


if __name__ == "__main__":
    main()
