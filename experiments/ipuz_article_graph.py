def формула(doc: Document, текст: str, номер: str) -> None:
    """Формула по принятой форме: по центру, номер в скобках справа."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.space_before, pf.space_after = Pt(6), Pt(6)
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.tab_stops.add_tab_stop(Cm(16.5), WD_TAB_ALIGNMENT.RIGHT)
    p.add_run(текст).italic = True
    p.add_run("\t(%s)" % номер)


