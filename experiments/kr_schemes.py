"""Схемы к описанию представления знаний: форма фигуры несёт смысл.

Четыре рисунка: пирамида уровней, конвейер исполнения, три состояния
свидетельства и ограничение целостности. Оформление общее —
``experiments.kr_style``.

Схемы строятся в ширине вставки (16 см, полоса набора), поэтому кегль в
коде — настоящие пункты на бумаге.

Запуск из корня репозитория::

    python -m experiments.kr_schemes
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from experiments.kr_style import (  # noqa: E402
    МЕЛК, ОСН, ТЕКСТ, выноска, карточка, панель, параллелограмм, ромб,
    сохранить, стрелка, трапеция, холст, шапка, шестиугольник)

ВЫХОД = ROOT / "outputs" / "14_статья_знания"
ПУСТО = "⊥"


# ---------------------------------------------------------------- рисунок 1
def kr1(путь: Path) -> None:
    """Пирамида уровней плюс сквозной пример одной цепочки."""
    fig, ax = холст(6.4)
    шапка(ax, "Пять уровней представления: от процесса к измерению",
          "синий", высота=10.0)

    ярусы = [
        ("Звенья процесса × этапы", "5 звеньев × 4 этапа",
         "зелёный", "Звено Н · этап III"),
        ("Геологические объекты", "20 объектов",
         "сирень", "О1 разломная зона"),
        ("Критерии с паспортом", "29 критериев",
         "охра", "К2 близость к зоне"),
        ("Признаки", "240 кодов", "синий", "расстояние до линии ↓"),
        ("Каналы на сетке 500 м", "113 543 ячейки", "серый",
         "растр, 5 375 км²"),
    ]
    верх, низ_п = 30.0, 50.0
    h, зазор, центр = 11.4, 1.1, 31.0
    y = 80.0
    for i, (имя, число, тон, пример) in enumerate(ярусы):
        y -= h
        ш_в = верх + i * (низ_п - верх) / 4.0
        ш_н = верх + (i + 1) * (низ_п - верх) / 4.0
        трапеция(ax, y, h, ш_в, ш_н, имя, низ=число, тон=тон, центр_x=центр,
                 кегль=ОСН - 0.4)
        карточка(ax, 62.0, y + 0.4, 21.0, h - 0.8, пример, тон=тон,
                 кегль=МЕЛК)
        стрелка(ax, 59.0, y + h / 2, 61.2, y + h / 2,
                толщина=1.1)
        y -= зазор

    ax.text(72.5, 81.0, "сквозной пример", ha="center", va="bottom",
            fontsize=МЕЛК, color=ТЕКСТ, style="italic")

    карточка(ax, 85.0, 47.0, 14.0, 23.0, "Условия\nнаблюдения",
             ["8 условий", "ведут только", "в C(x)"], тон="красный",
             центр=True, кегль=МЕЛК, полоса=7.0)
    карточка(ax, 85.0, 22.0, 14.0, 23.0, "Паспорт\nкритерия",
             ["направление", "радиус", "статус"], тон="жёлтый",
             центр=True, кегль=МЕЛК, полоса=7.0)
    выноска(ax, 24.0, 79.8, 20.0, 86.5,
            "«играет роль» — многие-ко-многим", тон="сирень")
    панель(ax, 1.0, 1.5, 98.0, 11.0, "Статусы утверждения связи",
           ["подтверждён человеком · отклонён · черновик модели · "
            "не удаётся проверить на доступных данных"])
    сохранить(fig, путь)


