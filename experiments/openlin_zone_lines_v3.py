    resp_fn = None
    min_len = MIN_LEN_M
    a.clean = a.clean or a.clean1k
    if a.clean:
        if not a.twin:
            raise SystemExit("чистка объявлена только поверх рабочего набора")
        from experiments.openlin_iso import oriented_response
        resp_fn = lambda im: oriented_response(im, CLEAN_ALONG_CELLS)
        p_max, n_sh = CLEAN_ALPHA, CLEAN_SHIFT_N
        n_total = CLEAN_N_TESTS_PRIOR + CLEAN_N_TESTS
