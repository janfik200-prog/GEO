def блок(ax, x, y, w, h, заголовок, полоса, строки) -> None:
    ax.add_patch(FancyBboxPatch(
        (x, y), w, h, boxstyle="round,pad=0,rounding_size=0.6",
        linewidth=1.0, edgecolor=РАМКА, facecolor=ПОЛОСА[полоса], zorder=2))
    ax.text(x + 0.7, y + h - 0.9, заголовок, ha="left", va="top",
            fontsize=КЕГЛЬ_БЛОК, color=ТЁМНЫЙ, fontweight="bold", zorder=3)
    шаг = 1.03
    yy = y + h - 2.6
    for текст, ново in строки:
        if ново:
            ax.add_patch(FancyBboxPatch(
                (x + 0.45, yy - 0.34), w - 0.9, 0.86,
                boxstyle="round,pad=0,rounding_size=0.25",
                linewidth=0.7, edgecolor=НОВОЕ_РАМКА,
                facecolor=НОВОЕ_ЗАЛИВКА, zorder=3))
        ax.text(x + 0.75, yy, текст, ha="left", va="center",
                fontsize=КЕГЛЬ_СТРОКА,
                color=НОВОЕ_РАМКА if ново else СЕРЫЙ,
                fontweight="bold" if ново else "normal", zorder=4)
        yy -= шаг


def стрелка(ax, x1, y1, x2, y2, стиль="-|>") -> None:
    ax.add_patch(FancyArrowPatch(
        (x1, y1), (x2, y2), arrowstyle=стиль, mutation_scale=11,
        linewidth=1.1, color=РАМКА, shrinkA=0, shrinkB=0, zorder=5))


