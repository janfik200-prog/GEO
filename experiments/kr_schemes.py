def kr4(путь: Path) -> None:
    """Ограничение целостности: один объект — одна роль в ячейке."""
    fig, ax = холст(6.4)
    шапка(ax, "Ограничение целостности: один объект — одна роль", "жёлтый",
          высота=10.5)

    карточка(ax, 1.0, 50.0, 22.0, 24.0, "Разломная зона",
             ["по генетической", "модели допустима", "в трёх звеньях"],
             тон="сирень", центр=True, кегль=ОСН - 0.2, полоса=6.8)
    варианты = [("Вариант И", "только источник", "45 % ячеек"),
                ("Вариант П", "только путь", "22 % ячеек"),
                ("Вариант Н", "только место накопления", "33 % ячеек")]
    for i, (т, н, доля) in enumerate(варианты):
        y = 71.0 - i * 15.5
        карточка(ax, 28.0, y, 33.0, 13.5, т, [н, доля], тон="синий",
                 центр=True, кегль=ОСН - 0.4, полоса=5.8)
        стрелка(ax, 23.4, 62.0, 27.4, y + 6.75, толщина=1.3)
        стрелка(ax, 61.4, y + 6.75, 66.4, 62.0, стиль=(0, (4, 2)),
                толщина=1.3)
    ромб(ax, 82.0, 62.0, 32.0, 26.0, "Выбор по ячейке:\nmax P(x)",
         тон="жёлтый", кегль=ОСН - 0.3, залить=True)

    панель(ax, 1.0, 1.5, 98.0, 24.0, "Формально",
           ["Индикатор a(o, z, x) ∈ {0, 1} с ограничением Σ по z a(o, z, x) "
            "≤ 1 для каждой пары «объект — ячейка»;",
            "допустимое назначение выбирается перебором вариантов, "
            "максимум по итоговой оценке ячейки.",
            "Без ограничения один слой даёт три независимых свидетельства, "
            "и карта вырождается в формулу,",
            "которая держится на пересечении тех же разломных зон."])
    сохранить(fig, путь)


