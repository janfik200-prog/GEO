def экр(s: str) -> str:
    return s.replace('"', "'")


def собрать_исходник() -> str:
    L: list[str] = []
    A = L.append
    A("vars: { d2-config: { layout-engine: elk; theme-id: 0 } }")
    A("direction: down")
    A("")
    A("classes: {")
    A("  узел: { style: { fill: \"#ffffff\"; stroke: \"#8699a8\"; "
      "stroke-width: 1; font-size: 19; border-radius: 6 } }")
    A("  ново: { style: { fill: \"#fcefdc\"; stroke: \"#b8690f\"; "
      "stroke-width: 3; font-size: 19; bold: true; "
      "font-color: \"#8a4e09\"; border-radius: 6 } }")
    A("}")
    A("")
    A("шапка: |md")
    A("  # Система прогноза золотого оруденения — работа за полгода")
    A("  Лист R-48-XI,XII, Анабарский щит. Внутри каждой дорожки этапы идут "
      "слева направо.")
    A("")
    A("  **Порядок работы:** I. Данные → II. Модели и оценка. "
      "III. Знания дают собственную мишень взамен чужой карты и возвращают "
      "её в «Мишени». IV. Опора обслуживает оба потока: паспорта признаков "
      "вниз, понятия и обоснования — в ветку знаний.")
    A("")
    A("  Оранжевым и ромбом отмечены компоненты — кандидаты в новизну. "
      "Новым заявляется **компонент**, а не система целиком.")
    A("| { style: { font-size: 24; stroke-width: 0 } }")
    A("")
    # Решётки вместо направлений: ELK не держит direction во вложенных
    # контейнерах, а grid задаёт геометрию точно. Связи внутри решётки D2
    # не рисует, поэтому порядок работы вынесен в шапку.
    A("sys: \"\" {")
    A("  grid-columns: 1")
    A("  grid-gap: 34")
    A("  style: { stroke-width: 0; fill: \"#ffffff\" }")
    for ключ, заг, цвет, этапы in ДОРОЖКИ:
        A("  %s: %s {" % (ключ, экр(заг)))
        A("    grid-rows: 1")
        A("    grid-gap: 22")
        A("    style: { fill: \"%s\"; stroke: \"#4a6880\"; stroke-width: 2; "
          "font-size: 27; bold: true; border-radius: 10 }" % цвет)
        for эк, эз, узлы in этапы:
            A("    %s: %s {" % (эк, экр(эз)))
            A("      grid-columns: 1")
            A("      grid-gap: 11")
            A("      style: { fill: \"#fbfcfd\"; stroke: \"#9aa9b6\"; "
              "stroke-width: 1; font-size: 21; bold: true; "
              "border-radius: 8 }")
            for i, (ярлык, ново) in enumerate(узлы):
                подпись = ("%s %s" % (РОМБ, экр(ярлык)) if ново
                           else экр(ярлык))
                A("      n%d: %s { class: %s }"
                  % (i, подпись, "ново" if ново else "узел"))
            A("    }")
        A("  }")
    A("}")
    A("")
    A("шапка -> sys: { style: { opacity: 0 } }")
    return "\n".join(L) + "\n"


def main() -> None:
    запасные = [r"C:\Program Files\D2\d2.exe",
                r"C:\Program Files\D2\bin\d2.exe"]
    d2 = shutil.which("d2") or next(
        (p for p in запасные if Path(p).exists()), "")
    if not d2:
        sys.exit("не найден d2: winget install Terrastruct.D2")
    ВЫХОД.mkdir(parents=True, exist_ok=True)
    ИСХОДНИК.write_text(собрать_исходник(), encoding="utf-8")
    for цель, доп in ((PNG, ["--scale", "0.5"]), (SVG, [])):
        р = subprocess.run(
            [d2, "--layout", "elk", "--theme", "0", "--pad", "50", *доп,
             str(ИСХОДНИК), str(цель)],
            capture_output=True, text=True, encoding="utf-8")
        if р.returncode:
            print(р.stdout, р.stderr, sep="\n")
            sys.exit("d2 завершился с кодом %d" % р.returncode)
    узлов = sum(len(у) for _, _, _, э in ДОРОЖКИ for _, _, у in э)
    новых = sum(н for _, _, _, э in ДОРОЖКИ for _, _, у in э for _, н in у)
    print("узлов: %d, из них кандидатов в новизну: %d" % (узлов, новых))
    print("png:", PNG)
    print("svg:", SVG)


if __name__ == "__main__":
    main()
