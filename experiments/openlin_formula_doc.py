#: Команды TeX, которые не являются переменными: оформление и операции.
_SERVICE = {
    "dfrac", "frac", "sqrt", "exp", "log", "max", "min", "arg", "left",
    "right", "qquad", "quad", "cdot", "times", "pm", "mp", "geq", "leq",
    "wedge", "in", "sum", "top", "mathrm", "mathbb", "mathcal", "bar", "hat",
    "odot", "sim", "dots", "circ", "angle", "Rightarrow", "leftrightarrow",
    "langle", "rangle", "nabla", "cos", "sin", "arctan", "km", "m", "1",
}


def missing(tex: str, syms: list[tuple[str, str]]) -> list[str]:
    """Символы формулы, которых нет ни в её таблице, ни в общих обозначениях.

    Проверка грубая (по вхождению подстроки), но своё дело делает: ловит
    случай, когда формулу дописали, а обозначение описать забыли.
    """
    described = " ".join(sym(s) for s, _ in syms)
    described += " " + " ".join(sym(s) for s, _ in COMMON)
    cmds = set(re.findall(r"\\([A-Za-z]+)", tex)) - _SERVICE
    # слова в оформляющих командах проверяются вместе с самой командой:
    # \mathbb{R} на выходе sym() даёт «ℝ», а не «R»
    words = {(g, w) for g, w in
             re.findall(r"\\(math(?:rm|cal|bb))\{(\w+)\}", tex)}
    # оформляющие команды вырезаются целиком: буква внутри \mathbb{R} — это не
    # отдельная переменная R, а часть обозначения ℝ
    plain = re.sub(r"\\math(?:rm|cal|bb)\{\w+\}", " ", tex)
    plain = re.sub(r"\\[A-Za-z]+", " ", plain)
    letters = set(re.findall(r"(?<![A-Za-z])([A-Za-z])(?![A-Za-z])", plain))
    out = []
    for g, w in sorted(words):
        if w in _SERVICE:
            continue
        if sym("$\\" + g + "{" + w + "}$") not in described:
            out.append(w)
    for t in sorted((cmds | letters) - _SERVICE):
        probe = sym("$\\" + t + "$") if t in cmds else t
        if probe not in described and t not in described:
            out.append(t)
    return sorted(set(out))


