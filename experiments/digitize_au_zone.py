"""Оцифровка «минерализованной зоны (золото)» с георастра ГГК-200 листа R-49-I,II.

Зачем. На собственном листе R-48-XI,XII золота нет ни в проявлениях, ни в легенде:
4 точки «Проявления» — урановые и редкоземельные (TR,Th,U и U,Ag), а все 50 меток
«Au» — это пробы (литохимические и шлиховые), которые по стоп-листу проекта
годятся только для заверки и в признаки не идут. Единственный золотой РУДНЫЙ
объект в округе нанесён на северо-восточном соседе R-49-I,II (Оленёкское
поднятие), и этот скрипт снимает его контур с георастра.

Как искали. Знак зоны в легенде Анабарской серии — замкнутая жирная линия с
разрывом, в разрыве индекс элемента без числа («Au»); похожий знак «ореолы
рассеяния шлихового опробования» отличается засечкой и подписью вида «5-Zn», а
шлиховая проба — это мелкий кружок с подписью рядом. Поэтому поиск шёл в два
шага: (1) мультишаблонный ZNCC по чернильной маске дал 43 подписи «Au»;
(2) заливка фона от рамки выделила 45 областей крупнее 15 000 px, замкнутых
жирными линиями, из них 27 имели подпись «Au» на границе. Визуальная проверка
всех 27 оставила ровно одну: остальные — многоугольники между разломами, рядом
с которыми случайно оказалась шлиховая проба.

Важная деталь растра: пиксель георастра анизотропен (≈14 м по долготе против
≈43 м по широте), знаки сплющены по вертикали втрое, и при просмотре 1:1 овал
зоны читается как пучок разломов. Контроль обязан идти на изображении с
восстановленной геометрией печати (вертикальное растяжение x3).

Автоматическая трассировка контура не удалась и в скрипт не вошла: внутренность
овала рассечена двумя разломами, из-за чего морфологические заливки рвут площадь
на части. Контур снят вручную по осевой линии знака (42 вершины), невязка с
жирной линией на контрольном наложении ≲150 м при размере ячейки сетки 500 м.

Результат прогона 05.08.2026:

- зона одна, у ручья Киенг-Юрях: 108.686-108.984 в.д., 71.930-71.973 с.ш.,
  вытянута на запад-северо-запад, длина 10.6 км, площадь 28.3 км2, средняя
  ширина 2.7 км;
- внутри контура лежат 6 шлиховых проб с золотом и отметка 348;
- ГЛАВНОЕ ограничение: R-49-I,II примыкает к нашему листу только углом, и зона
  лежит в его дальней части — 18.5-28.7 км восточнее меридиана края расчётной
  сетки и 72.5 км от ближайшего (северо-восточного) угла самой сетки. Это вне
  покрытия грав-маг сетки (грав_маг.pgrid), то есть вне всех признаков группы
  gm_*. Заверять на ней можно только методы, чьи признаки считаются из
  общедоступных источников (спутник, рельеф).

Запуск из корня: ``python -m experiments.digitize_au_zone``.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import rasterio
from PIL import Image, ImageDraw
from pyproj import CRS, Geod, Transformer

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cache_paths import GGK200  # noqa: E402
from src import config  # noqa: E402
from src.integro_grid import read_grid_proj4, read_pgrid  # noqa: E402

TIF = GGK200 / "R-49-I_II" / "r-49-iiigeologicheskayakarta.tif"
OUT = config.PROJECT_ROOT / "data" / "processed" / "au_zone_r49_i_ii.geojson"
QC = config.PROJECT_ROOT / "data" / "processed" / "au_zone_r49_i_ii_qc.png"

# Окно просмотра для контроля (строки, столбцы георастра).
BOX = (30, 250, 1680, 2720)

# Вершины по осевой линии жирного контура, (строка, столбец) георастра, по
# часовой стрелке от западного окончания. Разрыв с подписью «Au» приходится на
# вершину (125, 2010) — там линия прервана, и контур проведён по её створу.
VERTICES = [
    (163, 1782), (152, 1792), (147, 1810), (143, 1840), (139, 1875),
    (134, 1910), (128, 1965), (125, 2010), (119, 2050), (115, 2085),
    (108, 2135), (101, 2175), (95, 2215), (88, 2255), (82, 2300),
    (77, 2345), (73, 2390), (72, 2425), (74, 2450), (78, 2475),
    (85, 2500), (93, 2520), (103, 2550), (114, 2555), (124, 2548),
    (133, 2520), (141, 2500), (145, 2480), (150, 2450), (155, 2420),
    (160, 2380), (165, 2330), (169, 2280), (175, 2220), (180, 2150),
    (183, 2080), (184, 2010), (184, 1940), (182, 1880), (178, 1820),
    (171, 1792), (167, 1784),
]


def ring_lonlat(transform) -> np.ndarray:
    """Вершины контура в WGS84 по аффинному преобразованию георастра."""
    return np.array([transform * (c, r) for r, c in VERTICES])


def grid_corners_lonlat() -> np.ndarray:
    """Углы расчётной сетки прогноза в WGS84.

    Меры длины и площади считаются геодезически, а не в проекции сетки: её
    осевой меридиан 105 в.д., зона удалена от него на ~3.8 градуса, и на такой
    выноске поперечная Меркатора растягивает координаты на десятки процентов.
    """
    m = read_pgrid(config.GOLD_TARGET_PGRID)
    xs = [m.x0, m.x0 + (m.prf - 1) * m.dx]
    ys = [m.y0, m.y0 + (m.pic - 1) * m.dy]
    proj4 = read_grid_proj4(config.GOLD_TARGET_PGRID)
    back = Transformer.from_crs(CRS.from_proj4(proj4), CRS.from_epsg(4326),
                                always_xy=True)
    corners = [(x, y) for x in xs for y in ys]
    lon, lat = back.transform([c[0] for c in corners], [c[1] for c in corners])
    return np.c_[lon, lat]


def main() -> None:
    with rasterio.open(TIF) as src:
        tf = src.transform
        img = src.read()[:, BOX[0]:BOX[1], BOX[2]:BOX[3]].transpose(1, 2, 0)

    ll = ring_lonlat(tf)
    geod = Geod(ellps="krass")
    area_m2, _ = geod.polygon_area_perimeter(ll[:, 0], ll[:, 1])
    area_km2 = abs(area_m2) / 1e6
    ii, jj = np.triu_indices(len(ll), 1)
    _, _, dist = geod.inv(ll[ii, 0], ll[ii, 1], ll[jj, 0], ll[jj, 1])
    length_km = dist.max() / 1e3
    print(f"Зона: {len(VERTICES)} вершин, {ll[:, 0].min():.4f}-{ll[:, 0].max():.4f} в.д., "
          f"{ll[:, 1].min():.4f}-{ll[:, 1].max():.4f} с.ш.")
    print(f"Длина {length_km:.1f} км, площадь {area_km2:.1f} км2, "
          f"средняя ширина {area_km2 / length_km:.1f} км")

    gc = grid_corners_lonlat()
    _, _, dg = geod.inv(np.repeat(ll[:, 0], len(gc)), np.repeat(ll[:, 1], len(gc)),
                        np.tile(gc[:, 0], len(ll)), np.tile(gc[:, 1], len(ll)))
    lon_edge = gc[:, 0].max()
    _, _, d_edge = geod.inv(ll[:, 0], ll[:, 1],
                            np.full(len(ll), lon_edge), ll[:, 1])
    print(f"Сетка прогноза: {gc[:, 0].min():.3f}-{gc[:, 0].max():.3f} в.д., "
          f"{gc[:, 1].min():.3f}-{gc[:, 1].max():.3f} с.ш.")
    print(f"Зона восточнее края сетки на {d_edge.min() / 1e3:.1f}-"
          f"{d_edge.max() / 1e3:.1f} км по параллели, ближайший угол сетки — "
          f"{dg.min() / 1e3:.1f} км (признаки gm_* там не считаются)")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "type": "FeatureCollection",
        "crs": {"type": "name",
                "properties": {"name": "urn:ogc:def:crs:OGC:1.3:CRS84"}},
        "features": [{
            "type": "Feature",
            "properties": {
                "name": "Минерализованная зона (золото), руч. Киенг-Юрях",
                "sheet": "R-49-I,II",
                "source": "ГГК-200, Анабарская серия, георастр geokniga",
                "legend": "минерализованные зоны (золото)",
                "digitized": "2026-08-05, вручную по осевой линии знака",
                "area_km2": round(area_km2, 2),
                "length_km": round(length_km, 2),
            },
            "geometry": {"type": "Polygon",
                         "coordinates": [[[round(x, 6), round(y, 6)]
                                          for x, y in ll] +
                                         [[round(ll[0, 0], 6), round(ll[0, 1], 6)]]]},
        }],
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Записано: {OUT}")

    im = Image.fromarray(img).resize((BOX[3] - BOX[2], (BOX[1] - BOX[0]) * 3),
                                     Image.LANCZOS).convert("RGB")
    d2 = ImageDraw.Draw(im)
    pts = [(c - BOX[2], (r - BOX[0]) * 3) for r, c in VERTICES]
    d2.line(pts + [pts[0]], fill=(255, 0, 0), width=3)
    im.save(QC)
    print(f"Контроль (геометрия печати восстановлена, x3 по вертикали): {QC}")


if __name__ == "__main__":
    main()
