def describe(feat: str, grp: str) -> str:
    if feat in EXACT:
        return EXACT[feat]
    std = feat.endswith("_std")
    base = feat[:-4] if std else feat
    suf = " (std – внутриячеечная/межгодовая изменчивость)" if std else ""
    if std and base in EXACT:
        return EXACT[base] + suf

    for суффикс, текст in СЛУЖЕБНЫЕ.items():
        if feat.endswith("_" + суффикс) and feat[:-len(суффикс) - 1] in СЪЁМКИ:
            гр_ = feat[:-len(суффикс) - 1]
            уточнение = ОТБРАКОВКА.get(гр_, " (облака, тени, брак качества)") if суффикс == "valid_frac" else ""
            return f"{СЪЁМКИ[гр_]}: {текст}{уточнение} — служебный признак покрытия"
    if grp == "ast":
        m = re.match(r"ast_(b0[1-9])$", base)
        if m:
            return f"ASTER {ASTER_BANDS[m.group(1)]}, сырое отражение" + suf
        key = base.replace("ast_", "")
        if key in INDEX_MEANING:
            return f"ASTER: {INDEX_MEANING[key]}" + suf
    if grp == "s2":
        m = re.match(r"s2_(b\w+)$", base)
        if m and m.group(1) in S2_BANDS:
            return f"Sentinel-2 {S2_BANDS[m.group(1)]}, сырое отражение" + suf
        key = base.replace("s2_", "")
        if key in INDEX_MEANING:
            return f"Sentinel-2: {INDEX_MEANING[key]}" + suf
    if grp == "l8":
        key = base.replace("l8_", "")
        band_names = {"blue": "канал blue", "green": "канал green", "red": "канал red",
                      "swir16": "канал SWIR 1", "swir22": "канал SWIR 2"}
        if key in band_names:
            return f"Landsat 8/9 {band_names[key]}, сырое отражение" + suf
        if key in INDEX_MEANING:
            return f"Landsat 8/9: {INDEX_MEANING[key]}" + suf
    if grp == "ls":
        m = re.match(r"ls_(ch\d)$", base)
        if m:
            return f"Landsat 7 ETM+ {LS_BANDS[m.group(1)]}, сырое отражение"
    if grp == "gm":
        key = base.replace("gm_", "")
        if key in GM_FIELDS:
            return f"Грав/магниторазведка: {GM_FIELDS[key]}"
    if grp == "pf":
        key = base.replace("pf_", "")
        if key in PF_FIELDS:
            return f"Потенциальные поля: {PF_FIELDS[key]}"
        up = _pf_upward(key)
        if up:
            return f"Потенциальные поля: {up}"
    if grp == "s1":
        key = base.replace("s1_", "")
        pol = {"vv": "поляризация VV, дБ", "vh": "поляризация VH, дБ", "vv_vh": "отношение поляризаций VV/VH"}
        if key in pol:
            return f"Sentinel-1: обратное рассеяние, {pol[key]}" + suf
    if grp == "psr":
        key = base.replace("psr_", "")
        pol = {"hh": "поляризация HH", "hv": "поляризация HV", "hh_hv": "отношение поляризаций HH/HV"}
        if key in pol:
            return f"ALOS PALSAR-2: {pol[key]}" + suf
    return f"Признак группы \"{grp}\""


def geo_note(feat: str, grp: str) -> str:
    """Предметный (геологический/рудоконтролирующий) смысл признака —
    отдельно от технического описания в describe()."""
    if feat in GEO:
        return GEO[feat]
    std = feat.endswith("_std")
    base = feat[:-4] if std else feat
    suf = " (изменчивость в пределах ячейки — текстурный, не прямой минералогический признак)" if std else ""
    if std and base in GEO:
        return GEO[base] + suf

    for суффикс in СЛУЖЕБНЫЕ:
        if feat.endswith("_" + суффикс) and feat[:-len(суффикс) - 1] in СЪЁМКИ:
            return GEO_СЛУЖЕБНЫЕ
    if grp == "ast":
        if re.match(r"ast_b0[1-9]$", base):
            return GEO_RAW["ast"]
        key = base.replace("ast_", "")
        if key in GEO_INDEX:
            return GEO_INDEX[key] + suf
    if grp == "s2":
        if re.match(r"s2_b\w+$", base):
            return GEO_RAW["s2"]
        key = base.replace("s2_", "")
        if key in GEO_INDEX:
            return GEO_INDEX[key] + suf
    if grp == "l8":
        key = base.replace("l8_", "")
        if key in {"blue", "green", "red", "swir16", "swir22"}:
            return GEO_RAW["l8"]
        if key in GEO_INDEX:
            return GEO_INDEX[key] + suf
    if grp == "ls":
        if re.match(r"ls_ch\d$", base):
            return GEO_RAW["ls"]
    if grp == "gm":
        key = base.replace("gm_", "")
        if key in GEO_GM:
            return GEO_GM[key]
    if grp == "pf":
        key = base.replace("pf_", "")
        if key in GEO_PF:
            return GEO_PF[key]
        if _pf_upward(key):
            return GEO_PF_UP
    if grp == "s1" and base in GEO_RADAR:
        return GEO_RADAR[base] + suf
    if grp == "psr" and base in GEO_RADAR:
        return GEO_RADAR[base] + suf
    return "прямой геологической интерпретации не установлено — используется как часть кластера (см. презентацию «Признаковое пространство»)"


def classify(col: str) -> str:
    if col in FACTOR_COLS:
        return "factor"
    if col in OPT_COLS:
        return "opt"
    for grp in ("dem", "lin", "gm", "l8", "ls", "pf", "psr", "relief2", "s1", "s2",
                "ast", "mask", "astir"):
        if col.startswith(grp + "_"):
            return "ter" if grp == "dem" else grp
    if col in ("dist_dnl", "dist_dnara"):
        return "dist"
    raise ValueError(f"не классифицирован: {col}")


