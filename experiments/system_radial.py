    ax.text(99.0, 95.6, "%s охрой — то, что доработано или сделано "
            "не по умолчанию" % РОМБ, ha="right", va="top",
            fontsize=8.4, color=НОВ_ТЕКСТ, fontweight="bold")

    путь.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(путь, facecolor="white")
    plt.close(fig)
    всего = sum(len(п) for *_, п in кластеры)
    новых = sum(н for *_, п in кластеры for _, н in п)
    print("категорий: %d, компонентов: %d, помечено: %d"
          % (len(кластеры), всего, новых))
    print("нарисовано:", путь)


