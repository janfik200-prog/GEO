def _pf_upward(key: str) -> str | None:
    """Текст для продолжения вверх ``(gr|mag)_upN``; None — не тот шаблон."""
    m = re.match(r"(gr|mag)_up(\d+)$", key)
    if not m:
        return None
    поле = "поля силы тяжести" if m.group(1) == "gr" else "магнитного поля"
    return (f"продолжение {поле} вверх на {m.group(2)} км (спектр x exp(-|k|h)): "
            "короткопериодная локальная составляющая подавлена, остаётся вклад "
            "крупных и глубоких источников")

