# --- помощники ---------------------------------------------------------------
def _sl(deck, node, rubric, title, subtitle=None):
    return deck.slide(SEC, node, title, subtitle, rubric=rubric)


def prose(sl, x, y, w, h, items, size=9.5, gap=6):
    """Абзацы без маркеров. Элемент — строка или пара (жирное начало, остальное)."""
    tf = textbox(sl, x, y, w, h)
    for i, it in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        if i:
            p.space_before = __import__("pptx").util.Pt(gap)
        if isinstance(it, (tuple, list)):
            run(p, it[0], size, DARK, bold=True)
            run(p, it[1], size, TEXT)
        else:
            run(p, it, size, TEXT)
    return tf


def pic(sl, x, y, path, w=None, h=None, caption=None, maxb=4.95):
    with Image.open(str(path)) as im:
        ar = im.width / im.height
    if w is None:
        w = h * ar
    else:
        h = w / ar
    if y + h > maxb:
        h = maxb - y
        w = h * ar
    picture(sl, x, y, w, h, path, caption=caption)
    return w, h


def class_legend(sl, x, y, w):
    """Шкала классов перспективности (как на картах mapstyle) обычными фигурами."""
    from pptx.dml.color import RGBColor
    step = w / 5.0
    for k, (c, lab) in enumerate(zip(CLASS_COLORS, CLASS_LABELS)):
        rect(sl, x + k * step, y, 0.16, 0.12,
             RGBColor.from_string(c.lstrip("#").upper()), BORDER)
        tf = textbox(sl, x + k * step + 0.20, y - 0.02, step - 0.22, 0.16,
                     MSO_ANCHOR.MIDDLE)
        run(tf.paragraphs[0], lab, 8.5, GREY)


