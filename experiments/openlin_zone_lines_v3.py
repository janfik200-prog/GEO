    if a.channel == "ndvi":
        from experiments.openlin_winter import detrend
        nd = w["ndvi"].astype("float32")
        opt = detrend(nd, np.isfinite(nd), res_m)
        p_max, n_sh = NDVI_ALPHA, NDVI_SHIFT_N
        n_total = NDVI_N_TESTS_PRIOR + NDVI_N_TESTS
        tag = "_ndvi"
    else:
        opt = w["shade"].astype("float32")
        p_max, n_sh = SHIFT_P_MAX, SHIFT_N
        n_total = RED_N_TESTS_TOTAL
        tag = ""
    # «цепочки» объявлены и проверены для 12 сцен и красного канала; NDVI и
    # полный набор сцен прогонялись с мостиками и воспроизводятся так же
    a.chains = not a.bridges and not sfx and a.channel == "B04"
    # по умолчанию — рабочий набор (предел сдвига по близнецам)
