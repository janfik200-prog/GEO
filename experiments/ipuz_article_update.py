import docx
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm


# ------------------------------------------------------------------ утилиты
def set_text(p, text: str) -> None:
    """Заменить текст абзаца, сохранив оформление первого прогона."""
    runs = list(p.runs)
    if not runs:
        p.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r._element.getparent().remove(r._element)


def insert_after(p, text: str, style: str | None = None):
    """Вставить новый абзац сразу после ``p``."""
    new_p = copy.deepcopy(p._p)
    p._p.addnext(new_p)
    np_ = docx.text.paragraph.Paragraph(new_p, p._parent)
    for r in list(np_.runs):
        r._element.getparent().remove(r._element)
    if style:
        np_.style = style
    np_.add_run(text)
    return np_


def put_picture(p, path: Path, width_cm: float = 16.5) -> None:
    """Очистить абзац и вставить в него рисунок."""
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(path), width=Cm(width_cm))


def insert_figure_after(p, img: Path, caption: str, width_cm: float = 16.5,
                        fig_style: str = "Normal"):
    """Вставить после ``p`` абзац с рисунком и подпись под ним.

    Абзац рисунка получает ``fig_style``, а не стиль подписи: иначе он
    наследует оформление того абзаца, с которого скопирован.
    """
    fig_p = insert_after(p, "")
    fig_p.style = fig_style
    put_picture(fig_p, img, width_cm)
    cap_p = insert_after(fig_p, caption, style="Figure caption")
    return cap_p


