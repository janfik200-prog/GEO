from pptx.dml.color import RGBColor

from src.slides_inst import (
    SECTION_ACCENTS, IMG, ROOT, bullets, card, caps, line, node, picture, rect,
    PALE, PALE_BLUE, GREY, GREY_L, DARK,
)
from experiments.report_sections.db import _fit

COUNT = 4

DONE, WORK, TODO = "сделано", "в работе", "не начато"
GREEN = RGBColor(0x16, 0xA3, 0x4A)
GREEN_L = RGBColor(0xDC, 0xFC, 0xE7)
BLUE = SECTION_ACCENTS["общая"][0]
STYLE = {
    DONE: dict(fill=GREEN_L, border=GREEN),
    WORK: dict(fill=PALE_BLUE, border=BLUE),
    TODO: dict(fill=PALE, border=GREY_L),
}
FIG = ROOT / "outputs" / "report_figs"


def _picture_path():
    p = IMG / "02_критериальный_метод" / "criterial_prognoz_map.png"
    return p if p.exists() else None


def build(deck):
    # 1. Титул
    deck.title_slide(
        rubric="АНАБАРСКИЙ ЩИТ · ЛИСТ R-48-XI, XII",
        title="Отчёт по мини-проектам",
        lead="База данных, база знаний, линеаменты, прогнозирование",
        tagline="Метод прогноза золото-урановых узлов на основе машинного обучения",
        chips=[("БАЗА ДАННЫХ", 1.05), ("БАЗА ЗНАНИЙ", 1.05), ("ЛИНЕАМЕНТЫ", 1.0), ("ПРОГНОЗИРОВАНИЕ", 1.3)],
        facts=[("ПРОЕКТ", "Прогноз золото-урановых узлов"), ("ФОРМАТ", "Отчёт по технологической схеме")],
        date="10.2026", picture_path=_picture_path(),
        pic_caption="КРИТЕРИАЛЬНЫЙ ПРОГНОЗ", pic_sub="эталон для сравнения")

    # 2. Схема: порядок блоков
    sl = deck.slide("ТЕХНОЛОГИЧЕСКАЯ СХЕМА", "ПОРЯДОК РАБОТЫ", "Как идёт работа: блок за блоком",
                    "Стрелки показывают порядок. Цвет рамки — состояние, полоса сверху — раздел отчёта")

    def box(x, y, w, h, num, name, status, section, tsize=8.5):
        node(sl, x, y, w, h, f"{num}  {name}", status, tcolor=DARK, scolor=GREY,
             tsize=tsize, ssize=7.5, **STYLE[status])
        rect(sl, x, y, w, 0.05, SECTION_ACCENTS[section][0])

    def arrow(x1, y1, x2, y2):
        line(sl, x1, y1, x2, y2, color=GREY, lw=1.0)

    h = 0.55
    # первый ярус: постановка, эталон, две параллельные линии, соотнесение
    y_mid, y_db, y_kb = 2.42, 1.92, 2.62
    box(0.50, y_mid, 1.35, h, "1", "Постановка", DONE, "прогноз")
    box(2.10, y_mid, 1.35, h, "2", "Эталон", DONE, "прогноз")
    box(3.75, y_db - 0.07, 1.45, h, "3", "Агентная БД", DONE, "бд")
    box(5.40, y_db - 0.07, 1.45, h, "4", "Паспортизация", WORK, "бд")
    box(3.75, y_kb + 0.07, 1.45, h, "5", "База знаний", WORK, "бз")
    box(5.40, y_kb + 0.07, 1.45, h, "6", "Граф знаний", WORK, "бз")
    box(7.55, y_mid, 1.95, h, "7", "Соотнесение БД и БЗ", DONE, "прогноз")
    arrow(1.85, y_mid + h / 2, 2.10, y_mid + h / 2)
    arrow(3.45, y_mid + h / 2, 3.75, y_db - 0.07 + h / 2)
    arrow(3.45, y_mid + h / 2, 3.75, y_kb + 0.07 + h / 2)
    arrow(5.20, y_db - 0.07 + h / 2, 5.40, y_db - 0.07 + h / 2)
    arrow(5.20, y_kb + 0.07 + h / 2, 5.40, y_kb + 0.07 + h / 2)
    arrow(6.85, y_db - 0.07 + h / 2, 7.55, y_mid + h / 2 - 0.1)
    arrow(6.85, y_kb + 0.07 + h / 2, 7.55, y_mid + h / 2 + 0.1)

    # второй ярус: ветки 8A–8F
    branches = [
        ("8A", "Из литературы", WORK), ("8B", "Анализ данных", WORK),
        ("8C", "Пространство: инструмент", WORK), ("8D", "Пространство: объяснитель", WORK),
        ("8E", "Без учителя + граф", TODO), ("8F", "Поиск по аналогам", WORK),
    ]
    w8, gap = 1.42, 0.096
    y8 = 3.62
    arrow(8.52, y_mid + h, 8.52, y8 - 0.20)
    caps(sl, 0.50, y8 - 0.27, 6.0, "8  Экспериментальные ветки: идут параллельно, у каждой свой лучший вариант", GREY, 7.5)
    for k, (num, name, st) in enumerate(branches):
        box(0.50 + k * (w8 + gap), y8, w8, 0.58, num, name, st, "прогноз", tsize=7.5)
    arrow(1.37, y8 + 0.58, 1.37, 4.38)

    # третий ярус: сравнение, проверка, итог; линеаменты отдельно
    y9 = 4.38
    box(0.50, y9, 1.75, 0.5, "9", "Сравнение", WORK, "прогноз")
    box(2.65, y9, 1.75, 0.5, "10", "Проверка и перенос", WORK, "прогноз")
    box(4.80, y9, 1.75, 0.5, "11", "Рабочая точка", WORK, "прогноз")
    arrow(2.25, y9 + 0.25, 2.65, y9 + 0.25)
    arrow(4.40, y9 + 0.25, 4.80, y9 + 0.25)
    node(sl, 7.55, y9, 1.95, 0.5, "Линеаменты", "отдельный проект, в подготовке", tcolor=DARK,
         scolor=GREY, tsize=8.5, ssize=7.5, fill=PALE, border=SECTION_ACCENTS["линеаменты"][0])
    rect(sl, 7.55, y9, 1.95, 0.05, SECTION_ACCENTS["линеаменты"][0])
    # условные обозначения
    xx = 0.50
    for st in (DONE, WORK, TODO):
        rect(sl, xx, 5.03, 0.16, 0.10, STYLE[st]["fill"], STYLE[st]["border"])
        caps(sl, xx + 0.22, 5.01, 0.9, st, GREY, 7.5)
        xx += 1.0
    for sec, label in [("бд", "база данных"), ("бз", "база знаний"), ("прогноз", "прогнозирование"), ("линеаменты", "линеаменты")]:
        rect(sl, xx, 5.03, 0.16, 0.10, SECTION_ACCENTS[sec][0])
        caps(sl, xx + 0.22, 5.01, 1.3, label, GREY, 7.5)
        xx += 1.25

    # 3. Постановка (текст прежний)
    sl = deck.slide("УЗЕЛ 1 · ПОСТАНОВКА", "СТАРТ", "Постановка задачи",
                    "Это не расчёт, а договорённость о цели, задачах и о том, как будем оценивать результат")
    cw = 2.9
    items = [
        ("Цель", "Разработать новый ГИС-метод прогнозирования золото-урановых узлов на основе машинного обучения и нейросетей для Анабарского щита (лист R-48-XI, XII). Метод должен переноситься на другие территории, а не быть разовой картой под один участок."),
        ("Задачи", "Собрать данные по территории независимо от признаков критериального анализа. Двумя параллельными ветками, данными и знаниями, выйти на экспериментальные направления обучения. В каждом подобрать лучшую модель, сравнить кандидатов между собой, с критериальным методом ВНИГНИ и с геологической логикой. Построить карту районирования."),
        ("Критерии результата", "Сравнение с уже опробованным методом, критериальным анализом ВНИГНИ, и заключение геологов-предметников. Оба критерия равноправны: если цифры лучше, а геолог не согласен, успехом это не считается."),
    ]
    for k, (t, b) in enumerate(items):
        card(sl, 0.50 + k * (cw + 0.15), 1.95, cw, 2.9, t, body=b, tsize=10.5, bsize=9)

    # 4. Эталон
    sl = deck.slide("УЗЕЛ 2 · ЭТАЛОН", "ЭТАЛОН / КОНТРОЛЬ", "Критериальный метод на Python",
                    "Воссоздан отдельной задачей: из ГИС Интегро в код, который можно запускать на любой территории")
    p = FIG / "crit_wide.png"
    w, hh = _fit(p, 3.7, 2.75)
    picture(sl, 0.50, 1.88, w, hh, p, caption="БАЛЛ ФОРМУЛЫ",
            sub="красным — основной лист")
    bullets(sl, 4.05, 1.95, 5.45, 3.0, [
        ("", "Критериальный анализ ВНИГНИ работает в ГИС Интегро. Мы переписали его на Python с нуля: воспроизвели факторные слои и формулу, которая их объединяет, и сверяли результат с оригиналом шаг за шагом."),
        ("", "На основном листе наш расчёт и расчёт ГИС Интегро почти не отличаются: ранговая корреляция +0.984."),
        ("", "Затем то же самое посчитали на смежной территории к югу от листа. Организация сравнила наш прогноз со старым прогнозом ВНИГНИ и подтвердила, что они совпадают."),
        ("", "Без этого эталона сравнивать новый метод было бы не с чем. Он остаётся контролем на всех следующих шагах."),
    ], size=10, dot=deck.accent, space=6)
