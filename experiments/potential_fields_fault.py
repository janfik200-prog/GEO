def _augment_with_native_grid(df: pd.DataFrame, meta, log) -> pd.DataFrame:
    """Досчитать недостающие ``PF_COLS`` прямо из нативной сетки грав/магнитки.

    Ничего не скачивает: вход — ``config.GRAVMAG_PGRID``, уже на диске (когда он
    на диске). Отсутствие сетки — не ошибка прогона, а измеренное ограничение
    рабочего дерева, поэтому обрабатывается сообщением, а не исключением.
    """
    missing = [c for c in pf.PF_COLS if c not in df.columns]
    if not missing:
        return df
    if not config.GRAVMAG_PGRID.exists():
        log(f"нет {config.GRAVMAG_PGRID.name} — {len(missing)} из "
            f"{len(pf.PF_COLS)} трансформант не досчитать; "
            "считаем на том, что есть в датасете")
        return df
    log(f"досчитываю {len(missing)} трансформант из {config.GRAVMAG_PGRID.name}")
    extra = pf.potential_field_features(meta)
    add = [c for c in missing if c in extra.columns]
    return df.join(extra[add])


def main(n_shifts: int | None = None) -> None:
    t0 = time.time()

    def log(msg=""):
        print(f"[{time.time() - t0:5.0f}s] {msg}", flush=True)

    meta = integro_grid.read_pgrid(config.GOLD_TARGET_PGRID)
    df = _load_dataset()
    df = _augment_with_native_grid(df, meta, log)
    pool = np.where(cell_mask.build_valid_mask(df))[0]
    log(f"сетка {meta.prf}x{meta.pic}, валидных ячеек {pool.size}")

    targets = _targets(df, pool)
    for name, idx in targets.items():
        share = idx.size / pool.size
        ceiling = min(1.0, config.FZ_AREA / share) / config.FZ_AREA
        log(f"цель «{name}»: {idx.size} ячеек ({share:.1%} пула), "
            f"потолок lift@{config.FZ_AREA:.0%} = {ceiling:.2f}")

    scores, missing = pf.edge_tracer_scores(df)
    log(f"кандидатов посчитано {len(scores)}: {sorted(scores)}")
    if missing:
        log(f"НЕ ПОСЧИТАНЫ (нет колонок): {sorted(missing)} — "
            "знаменатель Бонферрони это НЕ уменьшает")

    n_tests = config.PF_N_TESTS_PRIOR + config.FZ_N_TESTS_PF
    alpha = 0.05 / n_tests
    log(f"накопительный знаменатель Бонферрони {n_tests} "
        f"(до этого прогона {config.PF_N_TESTS_PRIOR}: блок1 "
        f"{config.FZ_N_TESTS_BLOCK1} + 2C {config.FZ_N_TESTS_2C} + блок2 "
        f"{config.FZ_N_TESTS_BLOCK2} + задача №3 {config.FG_N_TESTS}; "
        f"свои {config.FZ_N_TESTS_PF}), alpha = {alpha:.6f}")
    n_shifts = n_shifts or config.FZ_N_SHIFTS
    p_min = 1.0 / (1.0 + n_shifts)
    log(f"минимально достижимое p при {n_shifts} сдвигах = {p_min:.5f} — "
        f"{'порог достижим' if p_min < alpha else 'ПОРОГ НЕДОСТИЖИМ, тест бессмыслен'}")
    if p_min >= alpha:
        raise SystemExit("увеличьте FZ_N_SHIFTS: тест не может быть пройден "
                         "ни при каком результате")

    controls = fz.relief_control_matrix(df)
    have = [c for c in config.FZ_RELIEF_CONTROLS if c in df.columns]
    log(f"контроли рельефа: {len(have)} колонок")

    planks = {n: _score_of(n, df, len(df)) for n in PLANKS
              if n == "random" or n in df.columns}
    rows = []
    for target_name, fault_idx in targets.items():
        log(f"--- цель «{target_name}» ---")
        for name, score in {**planks, **scores}.items():
            nan_frac = float(np.isnan(np.asarray(score, dtype=float)[pool]).mean())
            res = fz.screen_candidate(score, df, meta, fault_idx, pool,
                                      controls=controls, n_shifts=n_shifts)
            rows.append({"цель": target_name, "карта": name,
                         "планка": name in planks, "NaN": nan_frac, **res})
            log(f"  {name:12} lift={res['lift']:.3f} (p={res['p']:.4f})  "
                f"остаток lift={res['lift_resid']:.3f} (p={res['p_resid']:.4f})")

    out = pd.DataFrame(rows)
    out_path = ROOT / "outputs" / "metrics" / "potential_fields_fault.csv"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(out_path, index=False, encoding="utf-8-sig")

    _report(out, targets, pool, alpha, missing)
    log(f"сохранено: {out_path}")


def _report(out: pd.DataFrame, targets, pool, alpha: float, missing) -> None:
    print(f"\n{'=' * 86}\nПОТЕНЦИАЛЬНЫЕ ПОЛЯ ПРОТИВ КАРТЫ РАЗЛОМОВ "
          f"(alpha = {alpha:.6f})\n{'=' * 86}")
    for target_name, idx in targets.items():
        share = idx.size / pool.size
        ceiling = min(1.0, config.FZ_AREA / share) / config.FZ_AREA
        sub = out[out["цель"] == target_name].sort_values("lift_resid",
                                                          ascending=False)
        print(f"\nЦель: {target_name} — потолок метрики {ceiling:.2f}")
        print(f"{'карта':<14}{'NaN':>6}{'lift':>8}{'p':>9}"
              f"{'lift ост.':>11}{'p ост.':>9}  вердикт")
        for _, r in sub.iterrows():
            verdict = ("планка" if r["планка"] else
                       "ЗНАЧИМ после контроля" if r["p_resid"] < alpha else
                       "не значим после контроля")
            print(f"{r['карта']:<14}{r['NaN']:>5.0%}{r['lift']:>8.3f}{r['p']:>9.4f}"
                  f"{r['lift_resid']:>11.3f}{r['p_resid']:>9.4f}  {verdict}")

    cand = out[~out["планка"]]
    win = cand[cand["p_resid"] < alpha]
    print()
    if win.empty:
        print("ИТОГ: значимых после контроля рельефа НЕТ. Для профильного "
              "инструмента\nглубинного картирования это сильный отрицательный "
              "результат: потенциальные поля\nне находят закартированных разломов "
              "лучше случайной карты той же зернистости.")
    else:
        print("ИТОГ: значимые после контроля есть — "
              f"{', '.join(sorted(set(win['карта'])))}.")
        print("ЧИТАТЬ С ОГОВОРКОЙ config.PF_FAULT_PRIMARY, записанной ДО прогона:\n"
              "слои называются «глубинные разломы», и на щите их классически рисуют\n"
              "по этим же полям. Высокий lift здесь двусмыслен — «поля находят\n"
              "разломы» и «разломы нарисованы по полям» этим прогоном не различить.")
    if missing:
        print(f"\nНЕ ПРОВЕРЕНЫ (нет исходной сетки): {', '.join(sorted(missing))}.\n"
              f"Вернуть {config.GRAVMAG_PGRID.name} — и они досчитаются тем же "
              "прогоном\nбез изменения порога: их тесты в знаменателе уже учтены.")


if __name__ == "__main__":
    main()
