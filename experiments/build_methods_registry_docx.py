def _style(doc: Document) -> None:
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(10)
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    for m in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, m, Cm(1.6))


def _h(doc: Document, text: str, size: float, color=DARK, space_before: int = 14) -> None:
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(4)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(size)
    r.font.color.rgb = color


def _intro(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text)
    p.paragraph_format.space_after = Pt(8)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    for r in p.runs:
        r.font.size = Pt(9.5)


def _table(doc: Document, header: list, rows: list, widths: list) -> None:
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, name in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        r = cell.paragraphs[0].add_run(name)
        r.bold = True
        r.font.size = Pt(9)
        r.font.color.rgb = ACCENT
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val))
            r.font.size = Pt(8.5)
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def main() -> None:
    doc = Document()
    _style(doc)

    _h(doc, "Реестр опробованных методов и использованных данных", 20, ACCENT, 0)
    p = doc.add_paragraph()
    p.add_run("Проект: прогноз золото-урановых узлов методами машинного обучения. "
              "Территория — лист R-48-XI,XII (сетка 500 м, 22 946 ячеек) и смежная "
              "площадь четырёх листов Госгеолкарты-200 (90 597 ячеек). "
              "Составлено 04.09.2026.").font.size = Pt(10)
    _intro(doc, "Документ сводит в один файл все методы, опробованные в проекте, и "
                "данные, на которых считался каждый из них. Под «методом» здесь "
                "понимается отдельный алгоритм в отдельном прогоне, а не программа "
                "целиком: один прогон обычно считает от трёх до одиннадцати методов на "
                "одинаковых данных, чтобы сравнение шло между картами, а не между "
                "чужими публикациями. Числа не пересчитывались — они взяты из "
                "сохранённых таблиц метрик; в последнем столбце каждой таблицы указан "
                "прогон, где число можно проверить.")

    _h(doc, "I. Данные", 15)
    _h(doc, "I.1. Версии датасета", 12, DARK, 8)
    _table(doc, ["Датасет", "Размер", "Состав", "Для чего собран"], DATASETS,
           [3.6, 4.0, 9.5, 8.0])

    _h(doc, "I.2. Группы признаков и их источники", 12, DARK, 10)
    _table(doc, ["Группа", "Признаков", "Что это", "Источник", "Разрешение"], GROUPS,
           [3.0, 1.9, 10.0, 5.2, 5.0])

    _h(doc, "I.3. Мишени и метки", 12, DARK, 10)
    _table(doc, ["Мишень", "Объём", "Источник", "Примечание"], TARGETS,
           [5.0, 3.6, 6.0, 10.5])

    _h(doc, "I.4. Наборы признаков, использованные в обучении", 12, DARK, 10)
    _table(doc, ["Набор", "Что это", "Примечание"], FEATURE_SETS, [4.0, 7.0, 14.1])

    _h(doc, "II. Протоколы проверки", 15)
    _intro(doc, "Все результаты раздела III получены по одному из перечисленных "
                "протоколов. Без указания протокола цифра качества не имеет смысла: "
                "на сетке 500 м соседние ячейки почти одинаковы, и случайное разбиение "
                "измеряет не прогноз, а интерполяцию.")
    for name, text in PROTOCOLS:
        p = doc.add_paragraph(style="List Bullet")
        r = p.add_run(name + ". ")
        r.bold = True
        r.font.size = Pt(9.5)
        r2 = p.add_run(text)
        r2.font.size = Pt(9.5)

    _h(doc, "III. Опробованные методы", 15)
    for title, intro, rows in BLOCKS:
        _h(doc, title, 12.5, DARK, 12)
        _intro(doc, intro)
        _table(doc, ["Метод", "Что это", "Данные", "Как проверялся", "Результат", "Прогон"],
               rows, [4.2, 5.0, 5.2, 4.2, 5.6, 3.0])

    _h(doc, "IV. Итог", 15)
    for title, items in CLOSING:
        _h(doc, title, 12, DARK, 8)
        for it in items:
            p = doc.add_paragraph(it, style="List Bullet")
            p.paragraph_format.space_after = Pt(3)
            for r in p.runs:
                r.font.size = Pt(9.5)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    n = sum(len(rows) for _, _, rows in BLOCKS)
    print(f"OK: {OUT}")
    print(f"методов в реестре: {n}, блоков: {len(BLOCKS)}, "
          f"версий датасета: {len(DATASETS)}, групп признаков: {len(GROUPS)}")


if __name__ == "__main__":
    main()
