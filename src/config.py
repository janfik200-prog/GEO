# --- Второй оператор группировки: сгущения rho как пики плотности ---
# ЗАЧЕМ ВТОРОЙ. Оператор DBSCAN разделяет зоны по РАЗРЫВАМ в rho, а разрывы
# есть только у разреженного входа. ИЗМЕРЕНО на популяциях до сверки с целями:
# у 151 дайки медианный зазор в rho 0.42-1.35 км и зазоров шире порога 2-5 штук,
# а у 3087 рельефных линеаментов медианный зазор 26-56 МЕТРОВ и зазоров шире
# порога НЕТ НИ ОДНОГО ни в одной моде. То есть на плотном входе DBSCAN
# вырождается: вся мода обязана слиться в одну полосу во всю ширину листа.
# Это не свойство линеаментов, а свойство оператора, и накрывает оно любой
# будущий плотный вход — в том числе вектор разломов с растра ГГК-200, ради
# которого ветка и затевалась.
#
# Поэтому вводится второй оператор: зона — не связная компонента, а СГУЩЕНИЕ,
# то есть пик взвешенной длиной плотности rho, а границы зон — долины между
# пиками. Он определён на любом входе, и на разреженном ведёт себя как первый.
# Оба оператора пре-регистрированы ДО прогона и оба входят в знаменатель.
#
