def text(s, x, y, w, h, paras, anchor=MSO_ANCHOR.TOP, align=PP_ALIGN.LEFT,
         space=6, spacing=1.05):
    """Надпись из абзацев; абзац — список фрагментов
    (текст, кегль, цвет, жирный, курсив)."""
    tf = textbox(s, x, y, w, h, anchor)
    for i, runs in enumerate(paras):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.space_after = Pt(space)
        p.line_spacing = spacing
        for r in runs:
            t, size, color = r[0], r[1], r[2]
            bold = r[3] if len(r) > 3 else False
            italic = r[4] if len(r) > 4 else False
            set_run(p.add_run(), t, size, color, bold=bold, italic=italic)
    return tf


def card(s, x, y, w, h, fill, head, body, head_color=DARK, body_color=DARK,
         head_size=15, body_size=12.5, strip=None, pad=0.15,
         anchor=MSO_ANCHOR.TOP, align=PP_ALIGN.LEFT):
    """Карточка: скруглённая плашка, жирный заголовок и текст под ним.

    `body` — строка или список строк (абзацы); `strip` — цвет полосы слева.
    """
    round_rect(s, x, y, w, h, fill, radius=0.05)
    if strip is not None:
        rect(s, x, y, Pt(5), h, strip)
    paras = []
    if head:
        paras.append([(head, head_size, head_color, True)])
    for b in ([body] if isinstance(body, str) else body):
        paras.append([(b, body_size, body_color)])
    return text(s, x + I(pad), y + I(0.08), w - I(2 * pad), h - I(0.16),
                paras, anchor=anchor, align=align)


def arrow(s, x1, y1, x2, y2, color=GOLD, weight=2.25, both=False):
    """Прямая стрелка; `both` — наконечники на обоих концах."""
    cxn = connector(s, x1, y1, x2, y2, color, weight=weight)
    if both:
        ln = cxn.line._get_or_add_ln()
        ln.insert(0, ln.makeelement(qn("a:headEnd"),
                                    {"type": "triangle", "w": "med",
                                     "len": "med"}))
        # headEnd должен стоять перед tailEnd
        tail = ln.find(qn("a:tailEnd"))
        head = ln.find(qn("a:headEnd"))
        ln.remove(head)
        tail.addprevious(head)
    return cxn


def chain(s, y, h, boxes, gap=0.3, x0=MARGIN, total=CONTENT_W,
          head_size=14, body_size=11.5):
    """Ряд карточек одинаковой ширины со стрелками между ними.

    `boxes` — список (заливка, заголовок, текст, цвет текста).
    Возвращает левые края карточек и их ширину.
    """
    n = len(boxes)
    w = Emu((total - I(gap) * (n - 1)) // n)
    xs = []
    for i, (fill, head, body, fg) in enumerate(boxes):
        x = x0 + i * (w + I(gap))
        xs.append(x)
        card(s, x, y, w, h, fill, head, body, head_color=fg, body_color=fg,
             head_size=head_size, body_size=body_size, pad=0.13)
        if i:
            arrow(s, x - I(gap) + I(0.04), y + h // 2, x - I(0.04), y + h // 2)
    return xs, w


